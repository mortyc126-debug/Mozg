"""v0.35: РАЗНИЦА РАЗНИЦ -- действительно ли правило границы губит выигрыш
от строения, или вердикты просто разошлись по порогу.

ОТКУДА ВОПРОС. v0.33 и v0.34 отличались ровно одной ручкой, шли на одних
и тех же сидах и дали:
    правило ВКЛЮЧЕНО (v0.33): строение выше активности на +3.39 п.п.,
        15 из 24, p = 0.1537 -- вердикт НЕ вынесен;
    правило ВЫКЛЮЧЕНО (v0.34): +5.13 п.п., 17 из 24, p = 0.0320 --
        вердикт вынесен.
Соблазн прочесть это как "правило губит выигрыш" силён и НЕВЕРЕН. Два
условия по разные стороны порога p = 0.05 этим самым НЕ показаны
различными между собой: 3.39 и 5.13 отличаются на 1.74 п.п., и это
вполне может быть шумом. Ровно эта ловушка записана как урок №36, только
там порог был 5/6, а здесь 0.05.

ЧТО МЕРИТСЯ ЗДЕСЬ. Прямо то, о чём вопрос: разница разниц по каждому
сиду. Сиды одни и те же, ткань одна и та же, значит сравнение парное:
    d(сид) = (строение - активность)|правило выкл
           - (строение - активность)|правило вкл
Если правило губит выигрыш, d должно быть положительным у большинства
сидов.

ПРАВИЛО ЧТЕНИЯ, объявлено до запуска:
  * считается доля сидов с d > 0 и биномиальный p;
  * величина d в процентных пунктах сообщается рядом ВСЕГДА (урок №36);
  * если p >= 0.05 -- ПРАВИЛО НЕ ПОКАЗАНО ВИНОВНЫМ, и записывается
    именно так: вердикты v0.33 и v0.34 разошлись по порогу, а не по
    измеренному различию. Это не значит, что правило невиновно; это
    значит, что имеющиеся данные его не уличают;
  * сиды берутся ТЕ ЖЕ (2201-2224). Свежие тут не нужны и вредны:
    вопрос именно о том, как одна и та же ткань ведёт себя при двух
    значениях ручки.
"""
import sys
from math import comb

import numpy as np

sys.path.insert(0, "code")
import v33_activity_invites as v33


def main():
    on = dict(v33.GROW)
    off = dict(v33.GROW); off["state_affinity"] = 0.0

    print("=" * 70)
    print("ПРАВИЛО ВКЛЮЧЕНО")
    a = v33.run(GROW=on, SEEDS=v33.SEEDS, title="правило границы ВКЛЮЧЕНО")
    print("\n" + "=" * 70)
    print("ПРАВИЛО ВЫКЛЮЧЕНО")
    b = v33.run(GROW=off, SEEDS=v33.SEEDS, title="правило границы ВЫКЛЮЧЕНО")

    if a is None or b is None:
        print("\nодин из прогонов без отклика -- сравнивать нечего")
        return
    common = sorted(set(a["seeds"]) & set(b["seeds"]))
    ia = [a["seeds"].index(s) for s in common]
    ib = [b["seeds"].index(s) for s in common]
    ea = a["str"][ia] - a["uns"][ia]          # выигрыш строения, правило вкл
    eb = b["str"][ib] - b["uns"][ib]          # то же, правило выкл
    d = eb - ea
    n = len(common)
    k = int((d > 0).sum())
    p = sum(comb(n, i) for i in range(k, n + 1)) / 2 ** n

    print("\n" + "=" * 70)
    print(f"РАЗНИЦА РАЗНИЦ ({n} общих сидов):")
    print(f"  выигрыш строения при правиле ВКЛ:  {ea.mean() * 100:+.2f} п.п.")
    print(f"  выигрыш строения при правиле ВЫКЛ: {eb.mean() * 100:+.2f} п.п.")
    print(f"  разница:                           {d.mean() * 100:+.2f} п.п. "
          f"+- {d.std() * 100:.2f}")
    print(f"  d > 0 у {k} из {n}, p = {p:.4f}")
    if p < 0.05:
        print("  ПРАВИЛО 'РАЗЛИЧИЕ МЕШАЕТ СВЯЗИ' ГУБИТ ВЫИГРЫШ ОТ СТРОЕНИЯ")
    else:
        print("  ПРАВИЛО НЕ ПОКАЗАНО ВИНОВНЫМ: вердикты v0.33 и v0.34 "
              "разошлись по порогу, а не по измеренному различию")


if __name__ == "__main__":
    main()
