"""v0.38: экономна ли выросшая ткань -- проверка наблюдения из v0.37 на
свежих сидах, с правилом, объявленным ДО запуска.

ОТКУДА ВОПРОС. v0.37 сравнил выросшую ткань с брошенной жребием при
выравненных площади, численности и плотности. По ТОЧНОСТИ вердикт не
вынесен: +1.84 п.п. при шуме меры 2.04 п.п. Но в той же таблице бросилось
в глаза другое, чего правилом чтения заранее не объявлялось:

    доля ответивших узлов -- 0.162 у выросшей против 0.233 у брошенной,
    то есть на 44% ниже, при НЕ МЕНЬШЕЙ точности.

Замеченное после взгляда на числа вердикта не несёт -- поэтому здесь оно
проверяется заново: свежие сиды, правило объявлено до запуска.

ЧТО ЭТО ЗА ВЕЛИЧИНА. Проект давно держится меры "сколько можно прочесть
из состояния" (PRINCIPLES §2a). Здесь та же мера, делённая на цену:
сколько отделимости приходится на единицу отклика.

    экономность = (точность - 0.5) / доля ответивших

Это не украшение к точности, а самостоятельная величина цифрового
устройства. Живой ткани дешевизна отклика достаётся дорого -- каждый
лишний спайк стоит энергии; цифровой она не даётся даром, но и не
запрещена. Если выросшее расположение даёт то же чтение меньшей
активностью -- это первое, чем выросшая организация ЛУЧШЕ случайной, и
первый случай, когда расположение хоть в чём-то оказывается не пустым.

ПРАВИЛО ЧТЕНИЯ, объявлено до запуска:
  * главная величина -- ДОЛЯ ОТВЕТИВШИХ. Предсказание: у выросшей ткани
    ниже. Засчитывается при доле сидов с биномиальным p < 0.05 И
    относительной разнице не меньше 10% (порог назначен вдвое ниже
    замеченных 44%, чтобы не подгонять под увиденное);
  * вторая величина -- ЭКОНОМНОСТЬ. Предсказание: у выросшей выше. Те же
    условия засчитывания;
  * ТОЧНОСТЬ проверяется отдельно и служит предохранителем: если у
    выросшей ткани она окажется НИЖЕ больше чем на 2 п.п. (шум меры), то
    экономность куплена потерей чтения, и это записывается как размен, а
    не как выигрыш;
  * плотность выравнивается по числу соседей, проверка исполняемая, порог
    10% (уроки №30, №37);
  * перемешанные метки 0.42-0.58 (ошибка №40);
  * сиды СВЕЖИЕ (3201-3260) -- ни один не участвовал в v0.37.
"""
import sys

import numpy as np

sys.path.insert(0, "code")
import v31_learned_readability as v31
import v37_self_built as v37
from sim_core import simulate

N = v31.N
SEEDS = list(range(3201, 3261))
MIN_REL = 0.10


def main():
    keys = ("acc", "nul", "frac", "deg", "eco")
    res = {c: {k: [] for k in keys} for c in ("ВЫРОСШАЯ", "БРОШЕННАЯ ЖРЕБИЕМ")}
    skipped = 0
    for seed in SEEDS:
        g = simulate(seed=seed, **v37.GROWN)
        if g["born"] < N:
            skipped += 1
            continue
        base = {k: v for k, v in v37.GROWN.items()
                if k not in ("growth_by_division", "div_rate", "div_crowd")}
        r = simulate(seed=seed,
                     positions=v37.scattered_like(g["positions"][:N], N, seed),
                     **base)
        row = {}
        for name, net in (("ВЫРОСШАЯ", g), ("БРОШЕННАЯ ЖРЕБИЕМ", r)):
            p1, p2, surf = v31.interleaved(net["positions"])
            read = np.setdiff1d(np.arange(N), surf)
            C = net["contacts"] | net["contacts"].T
            f, a, nl = v31.measure(net, p1, p2, read, seed + 77)
            row[name] = (f, a, nl, float(C.sum(axis=1).mean()))
        if any(v[1] is None or v[0] <= 0 for v in row.values()):
            skipped += 1
            continue
        for name, (f, a, nl, deg) in row.items():
            res[name]["frac"].append(f); res[name]["acc"].append(a)
            res[name]["nul"].append(nl); res[name]["deg"].append(deg)
            res[name]["eco"].append((a - 0.5) / f)

    n = len(res["ВЫРОСШАЯ"]["acc"])
    print(f"{len(SEEDS)} свежих сидов ({n} в счёт, {skipped} отброшено)\n")
    print(f"{'ткань':<20} | {'соседей':>7} | {'отклик':>7} | {'точность':>8} | "
          f"{'экономность':>11} | {'перемешано':>10}")
    for c in res:
        print(f"{c:<20} | {np.mean(res[c]['deg']):7.2f} | "
              f"{np.mean(res[c]['frac']):7.3f} | {np.mean(res[c]['acc']):8.3f} | "
              f"{np.mean(res[c]['eco']):11.3f} | {np.mean(res[c]['nul']):10.3f}")
    if n == 0:
        print("\n  мерить не на чем")
        return

    G, R = res["ВЫРОСШАЯ"], res["БРОШЕННАЯ ЖРЕБИЕМ"]
    dg, dr = np.mean(G["deg"]), np.mean(R["deg"])
    mism = abs(dg - dr) / dr
    nul_all = np.mean(G["nul"] + R["nul"])
    print(f"\nплотность: расхождение {mism * 100:.2f}% (порог 10%); "
          f"перемешанные метки {nul_all:.3f}")
    if mism > 0.10 or not (0.42 <= nul_all <= 0.58):
        print("  проверки не пройдены -- вердикт не выносится")
        return

    fg, fr = np.array(G["frac"]), np.array(R["frac"])
    eg, er = np.array(G["eco"]), np.array(R["eco"])
    ag, ar = np.array(G["acc"]), np.array(R["acc"])
    kf = int((fg < fr).sum()); ke = int((eg > er).sum())
    pf, pe = v31.p_ge(kf, n), v31.p_ge(ke, n)
    relf = (fr.mean() - fg.mean()) / fr.mean()
    rele = (eg.mean() - er.mean()) / er.mean()
    print(f"\nЧТЕНИЕ ({n} сидов):")
    print(f"  отклик у выросшей НИЖЕ: {kf} из {n}, p = {pf:.4f} "
          f"({fr.mean():.3f} -> {fg.mean():.3f}, на {relf * 100:.1f}% меньше)")
    print(f"  экономность ВЫШЕ:       {ke} из {n}, p = {pe:.4f} "
          f"({er.mean():.3f} -> {eg.mean():.3f}, на {rele * 100:.1f}% больше)")
    print(f"  точность:               {ar.mean():.3f} -> {ag.mean():.3f} "
          f"({(ag - ar).mean() * 100:+.2f} п.п.)")
    if (ag - ar).mean() < -0.02:
        print("  РАЗМЕН, А НЕ ВЫИГРЫШ: экономность куплена потерей чтения")
    elif pf < 0.05 and relf >= MIN_REL and pe < 0.05 and rele >= MIN_REL:
        print("  ВЫРОСШАЯ ТКАНЬ ЭКОНОМНЕЕ: то же чтение меньшей активностью")
    elif pf < 0.05 and relf >= MIN_REL:
        print("  отклик ниже, но экономность порога не взяла")
    else:
        print("  наблюдение v0.37 на свежих сидах НЕ подтвердилось")


if __name__ == "__main__":
    main()
