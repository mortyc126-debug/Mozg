'use strict';
/* ЗНАК ДЕФОРМАЦИИ: какая точка агента становится больше и с какой она
   стороны относительно ориентации q.

   Проверяется СКОНСТРУИРОВАННЫМ примером, а не рассуждением: знак --
   ровно то место, где словесный вывод обманывает чаще всего.

   Ожидание, выведенное из кода:
     ось u = p2 - p1; proj = u.q;
     при proj > 0 точка p2 лежит со стороны +q, p1 -- со стороны -q;
     s = 0.5*k*proj > 0, поэтому r1 (на стороне -q) БОЛЬШЕ, r2 МЕНЬШЕ.
   Следовательно полоса толще со стороны -q и тоньше со стороны +q,
   а биметалл гнётся к ТОНКОЙ стороне, то есть К +q.
*/
const { bodyRadii, R, DEFAULTS } = require('../src/world');

let fails = 0;
const check = (name, ok, info) => {
  console.log(`${ok ? ' ok ' : 'СБОЙ'}  ${name}  ${info}`); if (!ok) fails++;
};

function agent(axis, q) {
  const L = Math.hypot(axis[0], axis[1]) || 1;
  return {
    p1x: 0, p1y: 0,
    p2x: axis[0] / L * 3.6, p2y: axis[1] / L * 3.6,
    qx: q[0], qy: q[1], pol: 1, amag: 1, r1: 0, r2: 0,
  };
}
const w = { p: { ...DEFAULTS, polarity: 0.35, bodyRadius: 0.72 } };

// 1. ось СОНАПРАВЛЕНА с q
{
  const c = agent([0, 1], [0, 1]);          // ось вверх, q вверх
  bodyRadii(w, c);
  // p1 внизу (сторона -q), p2 вверху (сторона +q)
  check('ось вдоль q: больше точка p1', c.r1 > c.r2,
    `r1=${c.r1.toFixed(3)} r2=${c.r2.toFixed(3)}`);
  check('  ...и p1 лежит со стороны -q', c.p1y < c.p2y,
    `p1y=${c.p1y.toFixed(2)} p2y=${c.p2y.toFixed(2)}`);
  check('  => толще со стороны -q, тоньше со стороны +q', c.r1 > c.r2 && c.p1y < c.p2y,
    'изгиб ожидается К +q');
}

// 2. ось ПРОТИВ q -- всё обязано перевернуться
{
  const c = agent([0, -1], [0, 1]);         // ось вниз, q вверх
  bodyRadii(w, c);
  check('ось против q: больше точка p2', c.r2 > c.r1,
    `r1=${c.r1.toFixed(3)} r2=${c.r2.toFixed(3)}`);
  check('  ...и p2 лежит со стороны -q', c.p2y < c.p1y,
    `p1y=${c.p1y.toFixed(2)} p2y=${c.p2y.toFixed(2)}`);
  check('  => снова толще со стороны -q', c.r2 > c.r1 && c.p2y < c.p1y,
    'вывод не зависит от того, как пронумерованы точки');
}

// 3. ось ПЕРПЕНДИКУЛЯРНА q -- деформации нет
{
  const c = agent([1, 0], [0, 1]);
  bodyRadii(w, c);
  check('ось поперёк q: деформации нет', Math.abs(c.r1 - c.r2) < 1e-12,
    `r1-r2=${(c.r1 - c.r2).toExponential(1)}`);
}

// 4. при выключенной полярности радиусы равны
{
  const w0 = { p: { ...DEFAULTS, polarity: 0, bodyRadius: 0.72 } };
  const c = agent([0, 1], [0, 1]);
  bodyRadii(w0, c);
  check('полярность выключена: радиусы равны', c.r1 === c.r2,
    `r1=${c.r1.toFixed(3)} r2=${c.r2.toFixed(3)}`);
}

console.log(fails
  ? `\nпровалено: ${fails}`
  : '\nВЫВОД: толстая сторона -- со стороны -q, тонкая -- со стороны +q.' +
    '\nБиметалл гнётся к тонкой стороне, то есть К +q.' +
    '\nНаблюдение (10 из 12 в сторону q) МЕХАНИЧЕСКИ ВЕРНО.' +
    '\nОшибочным было предсказание, а не модель.');
process.exit(fails ? 1 : 0);
