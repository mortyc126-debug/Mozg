"""v0.39: расположение против жребия -- сравнение, выравненное и по
времени жизни узла.

ОТКУДА. v0.37 и v0.38 сравнивали выросшую ткань со случайно рассыпанной,
выравняв площадь, число элементов и плотность связей. Оба вывода
оказались негодны, и по одной причине (запись об ошибке №43): у выросшей
ткани узлы рождаются делением и появляются в среднем на 5.13 секунды из
двенадцати, а у ткани сравнения все рождены в нуле. Условия отличались
двумя вещами сразу -- расположением И временем на развитие связей.

Это портит обе стороны:
  * отрицательный вывод v0.37 ("расположение не читается", +1.84 п.п.)
    мог быть следствием гандикапа выросшей ткани;
  * наблюдение v0.38 о меньшем отклике выросшей ткани объясняется проще
    поздним рождением, а не "экономностью".
К тому же две оценки одного и того же разошлись: +1.84 п.п. на сидах
v0.37 и +5.62 п.п. на сидах v0.38. Такого расхождения между независимыми
оценками одной величины быть не должно, и оно само по себе было поводом
искать невыравненное.

ЧТО ИСПРАВЛЕНО. В движок добавлен `birth_times`. Ткань сравнения получает
РАСПИСАНИЕ РОЖДЕНИЙ ВЫРОСШЕЙ, и различие сводится к одному расположению.
Совпадают: число элементов, площадь, плотность связей, расписание
рождений, поток случайных чисел. Отличается: выросло расположение или
брошено жребием.

ПРАВИЛО ЧТЕНИЯ, объявлено до запуска:
  * главная величина -- ТОЧНОСТЬ. Порог прежний: разница меньше 2 п.п.
    (шум меры) не читается как эффект (урок №42);
  * доля сидов с биномиальным p -- рядом всегда (урок №36);
  * плотность выравнивается по числу соседей, проверка исполняемая,
    порог 10% (уроки №30, №37);
  * ВРЕМЯ ЖИЗНИ проверяется тоже и тоже исполняемо: среднее время
    рождения в двух условиях обязано совпасть (иначе выравнивание не
    сработало);
  * перемешанные метки 0.42-0.58 (ошибка №40);
  * отклик и "экономность" сообщаются справочно и считаются ОТНОШЕНИЕМ
    СРЕДНИХ, а не средним отношений (ошибка №44);
  * сиды СВЕЖИЕ (3301-3400): ни один не участвовал ни в v0.37, ни в
    v0.38. Числа тех версий получены на нечестном сравнении и
    пересматриваться не могут -- их надо получать заново.
"""
import sys

import numpy as np

sys.path.insert(0, "code")
import v31_learned_readability as v31
import v37_self_built as v37
from sim_core import simulate

N = v31.N
SEEDS = list(range(3301, 3401))
MIN_EFFECT = 0.02


def main():
    keys = ("acc", "nul", "frac", "deg", "birth")
    res = {c: {k: [] for k in keys}
           for c in ("ВЫРОСШАЯ", "БРОШЕННАЯ ЖРЕБИЕМ")}
    skipped = 0
    for seed in SEEDS:
        g = simulate(seed=seed, **v37.GROWN)
        if g["born"] < N:
            skipped += 1
            continue
        base = {k: v for k, v in v37.GROWN.items()
                if k not in ("growth_by_division", "div_rate", "div_crowd")}
        r = simulate(seed=seed,
                     positions=v37.scattered_like(g["positions"][:N], N, seed),
                     birth_times=g["birth"], **base)
        row = {}
        for name, net in (("ВЫРОСШАЯ", g), ("БРОШЕННАЯ ЖРЕБИЕМ", r)):
            p1, p2, surf = v31.interleaved(net["positions"])
            read = np.setdiff1d(np.arange(N), surf)
            C = net["contacts"] | net["contacts"].T
            f, a, nl = v31.measure(net, p1, p2, read, seed + 77)
            row[name] = (f, a, nl, float(C.sum(axis=1).mean()),
                         float(net["birth"].mean()))
        if any(v[1] is None for v in row.values()):
            skipped += 1
            continue
        for name, (f, a, nl, deg, b) in row.items():
            res[name]["frac"].append(f); res[name]["acc"].append(a)
            res[name]["nul"].append(nl); res[name]["deg"].append(deg)
            res[name]["birth"].append(b)

    n = len(res["ВЫРОСШАЯ"]["acc"])
    print(f"{len(SEEDS)} свежих сидов ({n} в счёт, {skipped} отброшено); "
          f"расписание рождений у обоих условий одно и то же\n")
    print(f"{'ткань':<20} | {'соседей':>7} | {'рожд., с':>8} | {'отклик':>7} | "
          f"{'точность':>8} | {'перемешано':>10}")
    for c in res:
        print(f"{c:<20} | {np.mean(res[c]['deg']):7.2f} | "
              f"{np.mean(res[c]['birth']):8.2f} | "
              f"{np.mean(res[c]['frac']):7.3f} | {np.mean(res[c]['acc']):8.3f} | "
              f"{np.mean(res[c]['nul']):10.3f}")
    if n == 0:
        print("\n  мерить не на чем")
        return

    G, R = res["ВЫРОСШАЯ"], res["БРОШЕННАЯ ЖРЕБИЕМ"]
    dg, dr = np.mean(G["deg"]), np.mean(R["deg"])
    bg, br = np.mean(G["birth"]), np.mean(R["birth"])
    mism = abs(dg - dr) / dr
    nul_all = np.mean(G["nul"] + R["nul"])
    ag, ar = np.array(G["acc"]), np.array(R["acc"])
    fg, fr = np.mean(G["frac"]), np.mean(R["frac"])
    # экономность -- ОТНОШЕНИЕМ СРЕДНИХ (ошибка №44)
    eg = (ag.mean() - 0.5) / fg
    er = (ar.mean() - 0.5) / fr
    k = int((ag > ar).sum())
    p = v31.p_ge(k, n)
    print(f"\nпроверки: плотность {mism * 100:.2f}% (порог 10%); "
          f"рождение {bg:.2f} против {br:.2f} с; "
          f"перемешанные метки {nul_all:.3f}")
    print(f"справочно: экономность (отношение средних) "
          f"{er:.3f} -> {eg:.3f}")
    print(f"\nЧТЕНИЕ ({n} сидов):")
    print(f"  выросшая выше брошенной: {k} из {n}, p = {p:.4f} "
          f"({ar.mean():.3f} -> {ag.mean():.3f}, "
          f"{(ag - ar).mean() * 100:+.2f} п.п.)")
    if mism > 0.10:
        print("  ПЛОТНОСТЬ НЕ ВЫРАВНЕНА -- вердикт не выносится")
    elif abs(bg - br) > 0.01:
        print("  ВРЕМЯ ЖИЗНИ НЕ ВЫРАВНЕНО -- вердикт не выносится")
    elif not (0.42 <= nul_all <= 0.58):
        print(f"  перемешанные метки {nul_all:.3f} -- мера неисправна")
    elif max(ag.mean(), ar.mean()) < 0.52 or min(ag.mean(), ar.mean()) > 0.85:
        print("  пол или потолок -- вердикт не выносится")
    elif abs((ag - ar).mean()) < MIN_EFFECT:
        print(f"  разница меньше объявленного порога {MIN_EFFECT * 100:.0f} "
              "п.п. (шум меры) -- расположение не читается как эффект")
    elif p < 0.05:
        print("  ВЫРОСШЕЕ РАСПОЛОЖЕНИЕ ЧИТАЕТСЯ ЛУЧШЕ БРОШЕННОГО ЖРЕБИЕМ")
    else:
        print("  величина выше порога, но знак неустойчив -- читать осторожно")


if __name__ == "__main__":
    main()
