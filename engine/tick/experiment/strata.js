#!/usr/bin/env node
'use strict';
/* ============================================================
   РАССЛАИВАЮТСЯ ЛИ СКОРОСТИ САМИ

   Первый вопрос к среде, где дефицитен такт. Он внутренний: о том, что
   среда делает со своим же бюджетом, а не о похожести на что-либо.

   ЧТО МЕРЯЕТСЯ, три величины, все из собственной бухгалтерии мира:

     РАЗБРОС СКОРОСТЕЙ -- отношение стандартного отклонения скоростей
       частей к средней (скорость = обновлений на круг, по второй
       половине прогона, когда перенос кредита уже устоялся);
     ДЕРЖИТСЯ ЛИ ДЕЛЁЖ -- корреляция скорости части в третьей четверти
       прогона с её же скоростью в четвёртой. Ноль значит, что дележ
       всё время перетасовывается; единица -- что он застыл;
     ЗАХВАТ -- доля всех обновлений, доставшаяся одной, самой быстрой
       части. При 64 частях ровный дележ дал бы 1.56%.

   ПУСТОЙ ОТСЧЁТ -- ЖРЕБИЙ: такты раздаются случайно, без всякого
   правила. Он даёт ровно то, что даёт один случай, и всё сравнивается
   с ним. Отдельно печатается "поровну": там разброс обязан быть нулевым,
   это проверка исправности меры.

   ПРАВИЛО ЧТЕНИЯ, ОБЪЯВЛЕНО ДО ЗАПУСКА И ДВУСТОРОННЕЕ (правило для
   правил, введённое после choice.js: всякое правило обязано сказать,
   что означал бы противоположный знак):

     * РАССЛОЕНИЕ ЕСТЬ, если разброс скоростей ОТЛИЧЕН от жребия у
       большинства сидов при биномиальном p < 0.05. Сторона сообщается:
         ВВЕРХ -- скорости расходятся сильнее, чем от случая;
         ВНИЗ  -- дефицит ВЫРАВНИВАЕТ части сильнее, чем случай.
       Оба исхода содержательны: выравнивание означало бы, что перенос
       кредита гасит любое преимущество, и строить на нём нечего.
     * ДЕЛЁЖ ДЕРЖИТСЯ, если корреляция четвертей отлична от жребиевой у
       большинства при p < 0.05, с той же двусторонней оговоркой.

   ПРЕДСКАЗАНИЕ, ЗАПИСАННОЕ ДО ПРОГОНА. Я жду ЗАХВАТА при правиле
   "изменчивость": там положительная обратная связь -- меняешься сильнее,
   получаешь больше тактов, меняешься ещё сильнее. Если захвата не
   случится, предсказание не сбылось, и это записывается так же прямо,
   как если бы сбылось. Порог захвата объявляю здесь: одна часть берёт
   больше четверти всех обновлений.
   ============================================================ */
const fs = require('fs');
const { createTickWorld, run } = require('../world');

const N = 64, DEG = 3, ROUNDS = 400;
const BUDGET = 32;                    // вдвое меньше числа частей: дефицит настоящий
const SEEDS = [11, 22, 33, 44, 55, 66, 77, 88, 99, 110, 121, 132, 143, 154, 165, 176];
const RULES = ['жребий', 'изменчивость', 'устойчивость'];

/* скорость части за промежуток кругов -- по числу обновлений */
function measure(seed, rule) {
  const w = createTickWorld({ n: N, deg: DEG, seed, budget: BUDGET });
  const half = ROUNDS / 2, q3 = ROUNDS * 0.75;
  run(w, half, rule);
  const atHalf = w.parts.map((p) => p.steps);
  run(w, ROUNDS * 0.25, rule);
  const atQ3 = w.parts.map((p) => p.steps);
  run(w, ROUNDS * 0.25, rule);
  const end = w.parts.map((p) => p.steps);

  const sp = end.map((s, i) => (s - atHalf[i]) / (ROUNDS - half));
  const mean = sp.reduce((a, b) => a + b, 0) / N;
  const sd = Math.sqrt(sp.reduce((a, b) => a + (b - mean) ** 2, 0) / N);
  const cv = mean > 0 ? sd / mean : 0;

  const a = atQ3.map((s, i) => s - atHalf[i]);
  const b = end.map((s, i) => s - atQ3[i]);
  const ma = a.reduce((x, y) => x + y, 0) / N, mb = b.reduce((x, y) => x + y, 0) / N;
  let num = 0, da = 0, db = 0;
  for (let i = 0; i < N; i++) { num += (a[i] - ma) * (b[i] - mb); da += (a[i] - ma) ** 2; db += (b[i] - mb) ** 2; }
  const keep = (da > 0 && db > 0) ? num / Math.sqrt(da * db) : 0;

  const total = end.reduce((x, y) => x + y, 0);
  const grab = total > 0 ? Math.max(...end) / total : 0;
  return { cv, keep, grab, mean };
}

function pge(k, n) {
  const c = (n, k) => { let r = 1; for (let i = 0; i < k; i++) r = r * (n - i) / (i + 1); return r; };
  let s = 0; for (let i = k; i <= n; i++) s += c(n, i); return s / 2 ** n;
}

console.log('РАССЛАИВАЮТСЯ ЛИ СКОРОСТИ САМИ');
console.log(`${N} частей, ${DEG} соседа, бюджет ${BUDGET} тактов на круг (вдвое меньше частей)`);
console.log(`${ROUNDS} кругов, ${SEEDS.length} сидов\n`);

// исправность меры: при дележе поровну разброс обязан быть нулевым
const flat = measure(SEEDS[0], 'поровну');
console.log(`ПРОВЕРКА МЕРЫ (дележ поровну): разброс ${flat.cv.toFixed(6)}, ` +
  `захват ${(flat.grab * 100).toFixed(2)}% -- ${flat.cv < 1e-9 ? 'мера исправна' : 'МЕРА НЕИСПРАВНА'}`);

const data = [];
console.log('\n  сид |            разброс             |          держится дележ        |      захват');
console.log('      | жребий  изменч.  устойч.        | жребий  изменч.  устойч.       | изменч. устойч.');
for (const seed of SEEDS) {
  const r = {};
  for (const rule of RULES) r[rule] = measure(seed, rule);
  data.push({ seed, ...r });
  console.log(`${String(seed).padStart(5)} | ${r['жребий'].cv.toFixed(4)}  ${r['изменчивость'].cv.toFixed(4)}   ` +
    `${r['устойчивость'].cv.toFixed(4)}        | ${r['жребий'].keep.toFixed(3).padStart(6)}  ` +
    `${r['изменчивость'].keep.toFixed(3).padStart(6)}   ${r['устойчивость'].keep.toFixed(3).padStart(6)}       | ` +
    `${(r['изменчивость'].grab * 100).toFixed(1).padStart(5)}%  ${(r['устойчивость'].grab * 100).toFixed(1).padStart(5)}%`);
}

const n = data.length;
const mean = (f) => (data.reduce((s, d) => s + f(d), 0) / n).toFixed(4);
console.log(`\nсредние разброс: жребий ${mean((d) => d['жребий'].cv)}, ` +
  `изменчивость ${mean((d) => d['изменчивость'].cv)}, устойчивость ${mean((d) => d['устойчивость'].cv)}`);
console.log(`средние держится: жребий ${mean((d) => d['жребий'].keep)}, ` +
  `изменчивость ${mean((d) => d['изменчивость'].keep)}, устойчивость ${mean((d) => d['устойчивость'].keep)}`);
console.log(`средняя скорость: ${mean((d) => d['жребий'].mean)} обновлений на круг ` +
  `(бюджет/части = ${(BUDGET / N).toFixed(3)})`);

function twoSided(label, pick) {
  const up = data.filter((d) => pick(d) > 0).length;
  const dn = n - up;
  const p = pge(Math.max(up, dn), n);
  const sig = p < 0.05;
  console.log(`  ${label}: выше ${up}, ниже ${dn} из ${n}, p = ${p.toFixed(5)}` +
    (sig ? `  <- ОТЛИЧАЕТСЯ, ${up > dn ? 'ВВЕРХ' : 'ВНИЗ'}` : ''));
  return { sig, up, dn };
}

console.log('\nразброс против жребия:');
const cvI = twoSided('изменчивость', (d) => d['изменчивость'].cv - d['жребий'].cv);
const cvS = twoSided('устойчивость', (d) => d['устойчивость'].cv - d['жребий'].cv);
console.log('держится ли дележ, против жребия:');
const kI = twoSided('изменчивость', (d) => d['изменчивость'].keep - d['жребий'].keep);
const kS = twoSided('устойчивость', (d) => d['устойчивость'].keep - d['жребий'].keep);

const grabbed = data.filter((d) => d['изменчивость'].grab > 0.25).length;
console.log(`\nПРЕДСКАЗАНИЕ (захват при "изменчивости", порог 25% обновлений одной части):`);
console.log(`  сбылось на ${grabbed} сидах из ${n} -- ` +
  `${grabbed > n / 2 ? 'ПРЕДСКАЗАНИЕ СБЫЛОСЬ' : 'ПРЕДСКАЗАНИЕ НЕ СБЫЛОСЬ'}`);

const any = cvI.sig || cvS.sig;
console.log(`\n${any ? 'СКОРОСТИ РАССЛАИВАЮТСЯ НЕ КАК ОТ СЛУЧАЯ: правило начисления доходит до мира'
  : 'РАССЛОЕНИЯ НЕТ: ни одно правило не отличается от жребия'}`);
console.log('Какое правило ЛУЧШЕ -- опыт не говорит: "лучше" требует цели, а цели нет.');

fs.mkdirSync('tick/results', { recursive: true });
fs.writeFileSync('tick/results/strata.jsonl', data.map((d) => JSON.stringify(d)).join('\n') + '\n');
