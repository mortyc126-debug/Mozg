"""v0.21: адресуемость в МОЛЧАЩЕЙ подложке.

Три гипотезы о функциональной немоте опровергнуты (v0.19, v0.20): дело
не в линейке, не в отсутствии пространства в графе и не в слабости связи
самой по себе. Четвёртая нашлась при разведке и оказалась решающей.

ЧТО НАШЛОСЬ. Общая черта всех прежних прогонов: сеть ВСЕГДА занята --
5 Гц спонтанной активности, поддерживаемой гомеостазом. Импульс есть
малое возмущение поверх непрерывного шума. Постоянная спонтанная
активность -- черта биологической культуры: живая клетка не может
выключиться. Цифровой подложке это не нужно.

При токе 0.8 и выключенном гомеостазе сеть не разряжается ВОВСЕ (0
спайков за развитие). Тогда любой спайк в окне -- следствие импульса, и
фон равен нулю по построению. В этом режиме обнаружен ПОРОГ ПЕРЕДАЧИ и
за ним -- расширение отклика:

    сила | спайков | узлов ответило из 72 | расстояние ответивших
       8 |     3.4 |                  3.4 |                 0.245
      10 |    23.0 |                 21.4 |                 0.303
      12 |    68.2 |                 42.4 |                 0.335
      14 |   154.4 |                 64.6 |                 0.375
      16 |   227.0 |                 70.6 |                 0.401
      20 |   411.8 |                 71.8 |                 0.407

Отклик не просто появляется -- он РАСШИРЯЕТСЯ: среднее расстояние
ответивших растёт с 0.245 до 0.409 (0.409 -- это уже вся область). Это
первое в проекте пространственное распространение; требование Ф6 было
закрыто отрицательно в v0.12 и здесь получает другой ответ.

ОШИБКА, БЕЗ КОТОРОЙ ЭТОГО НЕ УВИДЕЛИ БЫ. Множитель силы связи сперва
был вписан только в simulate; у probe своя копия строки передачи, и
проба всегда шла при силе 1.0. Сила влияла на развитие сети, но не на
измерение. Обнаружено по тому, что при силе 256 отклик в молчащей сети
оставался ровно нулевым -- чего быть не может. Числа v0.20 получены с
этой ошибкой и НЕДЕЙСТВИТЕЛЬНЫ; развёртка перепрогоняется отдельно.

ЗДЕСЬ проверяется адресуемость в окне локального отклика (сила 8..12),
теми же мерами и контролями, что в v0.19.

ПРАВИЛО ЧТЕНИЯ, объявлено до запуска:
  * адресуемость установлена, если при силе, где отклик ЧАСТИЧЕН (доля
    ответивших узлов ниже 0.9), точность не ниже 0.65, а обе
    самопроверки около 0.5;
  * если точность высока только там, где отвечает ВСЯ сеть -- это не
    адресуемость, а общий разгон, и так и записывается;
  * если точность около 0.5 во всём окне -- четвёртая гипотеза тоже
    неверна.
"""
import importlib.util
import sys
import numpy as np

sys.path.insert(0, "code")
from sim_core import simulate

spec = importlib.util.spec_from_file_location("v19", "code/v19_addressability.py")
v19 = importlib.util.module_from_spec(spec)
spec.loader.exec_module(v19)

SEEDS = list(range(601, 611))
COUPLINGS = [8, 10, 12, 14, 16]
DRIVE = 0.8


def main():
    print(f"{len(SEEDS)} свежих seed'ов, ток {DRIVE}, гомеостаз выключен, "
          f"проб на класс {v19.TRIALS}\n")
    print(f"{'сила':>5} | {'спайков в развитии':>18} | {'доля ответивших':>16} | "
          f"{'точность':>17} | {'перемеш.':>9} | {'без передачи':>13}")
    rows = []
    for c in COUPLINGS:
        acc, shuf, notr, frac, dev = [], [], [], [], []
        for seed in SEEDS:
            r = simulate(seed=seed, drive=DRIVE, gradual_growth=False,
                         differentiation=0.5, homeostasis=False, coupling=c)
            a, b = v19.pick_groups(r["positions"])
            if a is None:
                continue
            keep = np.setdiff1d(np.arange(80), np.concatenate([a, b]))
            dev.append(int(r["spikes"].sum()))
            rng = np.random.default_rng(seed)
            noise = 0.012 * rng.standard_normal((int(v19.DUR / v19.DT), 80))
            from sim_core import probe
            sp = probe(r, noise, a, stimulus=True, coupling=c)
            frac.append(float((sp[500:1200][:, keep].sum(axis=0) > 0).mean()))
            acc.append(v19.accuracy(r, a, b, keep, np.random.default_rng(seed),
                                    coupling=c))
            shuf.append(v19.accuracy(r, a, b, keep, np.random.default_rng(seed),
                                     shuffle=True, coupling=c))
            notr.append(v19.accuracy(r, a, b, keep, np.random.default_rng(seed),
                                     transmission=False, coupling=c))
        rows.append((c, np.mean(acc), np.mean(frac), np.mean(shuf), np.mean(notr)))
        print(f"{c:>5} | {np.mean(dev):>18.0f} | {np.mean(frac):>16.3f} | "
              f"{np.mean(acc):>7.3f} +- {np.std(acc):.3f} | {np.mean(shuf):>9.3f} | "
              f"{np.mean(notr):>13.3f}")

    print("\nЧТЕНИЕ ПО ОБЪЯВЛЕННОМУ ПРАВИЛУ:")
    partial = [(c, a, f) for c, a, f, s_, n_ in rows if f < 0.9]
    if not partial:
        print("  режимов с ЧАСТИЧНЫМ откликом нет -- читать нечего")
        return
    c, a, f = max(partial, key=lambda x: x[1])
    ok = all(abs(s_ - 0.5) < 0.1 and abs(n_ - 0.5) < 0.1 for _, _, _, s_, n_ in rows)
    print(f"  самопроверки: {'пройдены' if ok else 'НЕ ПРОЙДЕНЫ -- результат не читается'}")
    if ok:
        print(f"  лучшая точность при частичном отклике: {a:.3f} "
              f"(сила {c}, ответило {f:.2f} сети)")
        print(f"  адресуемость: {'ЕСТЬ' if a >= 0.65 else 'НЕТ'}")


if __name__ == "__main__":
    main()
