import sys
import numpy as np

sys.path.insert(0, "code")
from sim_core import simulate

N = 80
SEEDS = list(range(11, 23))
DRIVE_MEAN = 1.175          # середина прежнего разброса 1.10..1.25


def tail_rates(spikes, dt, frac=0.5):
    """Частота каждого узла на последней части прогона."""
    steps = spikes.shape[0]
    tail = spikes[int(steps * frac):]
    return tail.sum(axis=0) / (tail.shape[0] * dt)


def r2_on_degree(threshold, contacts):
    """Доля разброса порога, объяснённая числом контактов узла."""
    deg = contacts.sum(axis=1).astype(float)
    if deg.std() == 0 or threshold.std() == 0:
        return float("nan")
    r = np.corrcoef(deg, threshold)[0, 1]
    return float(r * r)


def run(seed, cond):
    kw = dict(seed=seed)
    if cond in ("B", "C", "C0"):
        kw["drive"] = DRIVE_MEAN
    if cond in ("C", "C0"):
        kw["gradual_growth"] = False
    if cond == "C0":
        kw["transmission"] = False
    res = simulate(**kw)
    th = res["state"]["threshold"]
    rates = tail_rates(res["spikes"], res["dt"])
    return {
        "th_std": float(th.std()),
        "th_mean": float(th.mean()),
        "rate_std": float(rates.std()),
        "rate_mean": float(rates.mean()),
        "silent": float(np.mean(rates == 0)),
        "r2_deg": r2_on_degree(th, res["contacts"]),
        "deg": float(res["contacts"].sum(axis=1).mean()),
    }


def main():
    conds = ["A", "B", "C", "C0"]
    names = {"A": "выдано всё", "B": "drive одинаков",
             "C": "ВСЁ ОДИНАКОВО", "C0": "то же, без связи"}
    rows = {c: [] for c in conds}
    for seed in SEEDS:
        for c in conds:
            rows[c].append(run(seed, c))

    def col(c, k):
        return np.array([r[k] for r in rows[c]])

    print(f"{'условие':<18} | {'разброс порога':>15} | {'частота':>8} | "
          f"{'разброс частоты':>16} | {'молчат':>7} | {'соседей':>8} | "
          f"{'R^2 на степень':>14}")
    for c in conds:
        print(f"{names[c]:<18} | {col(c,'th_std').mean():>8.5f} +- {col(c,'th_std').std():.5f} | "
              f"{col(c,'rate_mean').mean():>8.3f} | {col(c,'rate_std').mean():>16.4f} | "
              f"{col(c,'silent').mean():>7.3f} | {col(c,'deg').mean():>8.2f} | "
              f"{np.nanmean(col(c,'r2_deg')):>14.4f}")

    a, cc, c0 = col("A", "th_std"), col("C", "th_std"), col("C0", "th_std")
    thr = int(np.ceil(len(SEEDS) * 5 / 6))
    print(f"\nЧТЕНИЕ ПО ОБЪЯВЛЕННОМУ ПРАВИЛУ ({len(SEEDS)} seed'ов, порог {thr}):")
    ratio = cc.mean() / a.mean()
    print(f"  разброс в C относительно A: {ratio:.3f} "
          f"({'НИЖЕ 10% -- различия выданы' if ratio < 0.10 else 'выше 10%'})")
    up = int((cc > c0).sum())
    print(f"  C превышает C0 (без связи): {up} из {len(SEEDS)} "
          f"({'взаимодействие порождает различие' if up >= thr else 'НЕ ПОДТВЕРЖДЕНО'}); "
          f"{cc.mean():.5f} против {c0.mean():.5f}")
    r2 = np.nanmean(col("C", "r2_deg"))
    print(f"  доля разброса, объяснённая степенью узла, в C: {r2:.4f} "
          f"({'СЧИТЫВАНИЕ ГЕОМЕТРИИ, не приобретённое состояние' if r2 > 0.8 else 'не сводится к степени'})")


if __name__ == "__main__":
    main()
