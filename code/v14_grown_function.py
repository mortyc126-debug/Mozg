import sys
import numpy as np

sys.path.insert(0, "code")
from sim_core import simulate
from v03_cyclic_shift import cyclic_shift_control
from v13_morphogenesis import grow_positions, nn_distances

N = 80
R_REF = 0.25
SEEDS = list(range(11, 23))          # 12 seed'ов


def mean_degree(pos, r):
    d = np.linalg.norm(pos[:, None, :] - pos[None, :, :], axis=2)
    np.fill_diagonal(d, np.inf)
    return float((d < r).sum(axis=1).mean())


def scale_to_match(grown, target_deg, r=R_REF, lo=0.2, hi=8.0, iters=60):
    """Растянуть облако вокруг центра до совпадения ЧИСЛА СОСЕДЕЙ.

    Выравнивать по расстоянию до ближайшего соседа нельзя: у выросшего
    облака оно больше, а область меньше, и меры расходятся.
    """
    c = grown.mean(axis=0)
    for _ in range(iters):
        mid = (lo + hi) / 2
        if mean_degree(c + (grown - c) * mid, r) > target_deg:
            lo = mid                      # растянуть сильнее
        else:
            hi = mid
    return c + (grown - c) * ((lo + hi) / 2)


def radius_for_degree(pos, target_deg, lo=0.01, hi=1.5, iters=60):
    """Подобрать радиус, дающий заданное среднее число соседей."""
    for _ in range(iters):
        mid = (lo + hi) / 2
        if mean_degree(pos, mid) < target_deg:
            lo = mid
        else:
            hi = mid
    return (lo + hi) / 2


def coordination(spikes, dt, seed):
    r = cyclic_shift_control(spikes, dt, n_shuffles=100, seed=seed)
    return r["q_ratio"], r["p_value"]


def main():
    rows = []
    print(f"{'seed':>5} | {'условие':<16} | {'соседей':>8} | {'частота':>8} | "
          f"{'молчат':>7} | {'согласование q':>14} | {'p':>6}")
    for seed in SEEDS:
        uni = np.random.default_rng(seed).uniform(0, 1, size=(N, 2))
        grown = grow_positions(seed=seed)
        deg_ref = mean_degree(uni, R_REF)

        conds = {
            "равномерные": (uni, R_REF),
            "выросшие, как есть": (grown, R_REF),
            "выросшие, МАСШТАБ": (scale_to_match(grown, deg_ref), R_REF),
            "выросшие, РАДИУС": (grown, radius_for_degree(grown, deg_ref)),
        }
        rec = {"seed": seed, "deg_ref": deg_ref}
        for name, (pos, r) in conds.items():
            res = simulate(seed=seed, positions=pos, contact_radius=r)
            q, p = coordination(res["spikes"], res["dt"], seed)
            m = res["metrics"]
            deg = mean_degree(pos, r)
            rec[name] = {"deg": deg, "q": q, "p": p,
                         "rate": m["rate_hz"], "silent": m["silent_fraction"]}
            print(f"{seed:>5} | {name:<16} | {deg:>8.2f} | {m['rate_hz']:>8.3f} | "
                  f"{m['silent_fraction']:>7.3f} | {q:>14.4f} | {p:>6.3f}")
        rows.append(rec)
        print()

    print("=" * 96)
    names = ["равномерные", "выросшие, как есть", "выросшие, МАСШТАБ", "выросшие, РАДИУС"]
    print(f"{'условие':<20} | {'соседей':>8} | {'частота':>8} | {'согласование q':>15} | "
          f"{'выше равномерных':>17}")
    ref_q = np.array([r["равномерные"]["q"] for r in rows])
    for nm in names:
        deg = np.array([r[nm]["deg"] for r in rows])
        q = np.array([r[nm]["q"] for r in rows])
        rate = np.array([r[nm]["rate"] for r in rows])
        up = int((q > ref_q).sum())
        print(f"{nm:<20} | {deg.mean():>8.2f} | {rate.mean():>8.3f} | "
              f"{q.mean():>7.4f} +- {q.std():.4f} | {up:>10} из {len(rows)}")

    print("\nПРОВЕРКА ВЫРАВНИВАНИЯ (порог 10%):")
    for nm in names[1:]:
        deg = np.array([r[nm]["deg"] for r in rows])
        ref = np.array([r["deg_ref"] for r in rows])
        rel = np.abs(deg - ref) / ref
        print(f"  {nm:<20}: расхождение с эталоном {rel.mean() * 100:>6.2f}% "
              f"(макс {rel.max() * 100:.2f}%) -- "
              f"{'ЧИТАЕМО' if rel.max() <= 0.10 else 'НЕ ЧИТАЕМО'}")

    print("\nЧТЕНИЕ ПО ОБЪЯВЛЕННОМУ ПРАВИЛУ (порог 5/6 = "
          f"{int(np.ceil(len(rows) * 5 / 6))} из {len(rows)}):")
    for nm in names[1:]:
        q = np.array([r[nm]["q"] for r in rows])
        up = int((q > ref_q).sum())
        maj = max(up, len(rows) - up)
        print(f"  {nm:<20}: в одну сторону {maj} из {len(rows)} "
              f"({'выше' if up >= len(rows) - up else 'ниже'} равномерных), "
              f"медиана отношения {np.median(q / ref_q):.4f}")


if __name__ == "__main__":
    main()
