"""v0.20: зависит ли АДРЕСУЕМОСТЬ от силы связи.

v0.19 дал отрицательный ответ: по активности остальных узлов нельзя
сказать, какой участок получил импульс (0.559 против 0.562 в контроле
при случайном уровне 0.5). Две гипотезы о причине были проверены и
опровергнуты: немота не в линейке (мера заменена на цифровую -- осталась)
и не в отсутствии пространства (шагов между узлами до семи, связь с
расстоянием r = 0.95).

Остался третий кандидат, и он теперь измерен: узел определяется СОБОЙ, а
не соседями. Доля входа, приходящая от сети, составляет 0.0081 -- меньше
процента. Собственный ток 1.175 при пороге около 1; сеть добавляет к
нему сотые доли. Распространяться нечему.

ЗАМЕЧАНИЕ ОБ УСТРОЙСТВЕ ПРОВЕРКИ. Первая попытка ввести ручку силы
масштабировала потолок веса (0.08) и бюджет входа (0.6) и НЕ ДЕЙСТВОВАЛА
вовсе: эти пределы не связывают -- вес нового контакта 0.015, при 12
соседях суммарный вход около 0.18. Все меры совпадали до знака при силе
от 1 до 16. Ручка перенесена туда, где связь входит в динамику:
syn += coupling * W[:, fired].sum(axis=1).

РЕЖИМЫ (seed 501), измерены до основного прогона:

    сила | частота | доля входа от сети | population_cv
       1 |   5.025 |             0.0081 | 0.383
       2 |   4.994 |             0.0183 | 0.785
       4 |   5.019 |             0.0230 | 1.576
       8 |   5.025 |             0.1123 | 2.236
      16 |   5.025 |             0.1376 | 1.795
      32 |   9.675 |             0.5492 | 2.165   <- гомеостаз не держит
      64 |  18.625 |             1.2529 | 2.147   <- разгон

ПРАВИЛО ЧТЕНИЯ, объявлено до запуска:
  * сеть считается здоровой при частоте 4..6 Гц и отсутствии молчащих
    узлов; вне этого условие не читается, сколь бы ни была точность;
  * адресуемость появляется, если при какой-либо ЗДОРОВОЙ силе точность
    не ниже 0.65 (тот же порог, что в v0.19);
  * если при всех здоровых силах точность остаётся около 0.5 -- третья
    гипотеза тоже неверна, немота не объясняется слабостью связи, и
    записывается именно это;
  * самопроверки обязательны при каждой силе: без передачи около 0.5 и
    перемешанные метки около 0.5.
"""
import importlib.util
import sys
import numpy as np

sys.path.insert(0, "code")
from sim_core import simulate

spec = importlib.util.spec_from_file_location("v19", "code/v19_addressability.py")
v19 = importlib.util.module_from_spec(spec)
spec.loader.exec_module(v19)

SEEDS = list(range(501, 507))
COUPLINGS = [1, 4, 8, 16, 32]
ETA = 0.5


def main():
    print(f"{len(SEEDS)} seed'ов, проб на класс {v19.TRIALS}, "
          f"признаков {(80 - 2 * v19.GROUP) * v19.BINS}\n")
    print(f"{'сила':>5} | {'частота':>8} | {'молчат':>7} | {'вход от сети':>13} | "
          f"{'точность':>17} | {'перемеш.':>9} | {'без передачи':>13} | здорова")
    rows = []
    for c in COUPLINGS:
        acc, shuf, notr, rate, sil, frac = [], [], [], [], [], []
        for seed in SEEDS:
            r = simulate(seed=seed, drive=1.175, gradual_growth=False,
                         differentiation=ETA, coupling=c)
            a, b = v19.pick_groups(r["positions"])
            if a is None:
                continue
            keep = np.setdiff1d(np.arange(80), np.concatenate([a, b]))
            acc.append(v19.accuracy(r, a, b, keep, np.random.default_rng(seed)))
            shuf.append(v19.accuracy(r, a, b, keep, np.random.default_rng(seed),
                                     shuffle=True))
            notr.append(v19.accuracy(r, a, b, keep, np.random.default_rng(seed),
                                     transmission=False))
            rate.append(r["metrics"]["rate_hz"])
            sil.append(r["metrics"]["silent_fraction"])
            h = r["history"]
            frac.append(h[len(h) // 2:, 4].mean())
        healthy = 4.0 <= np.mean(rate) <= 6.0 and np.mean(sil) == 0.0
        rows.append((c, np.mean(acc), healthy))
        print(f"{c:>5} | {np.mean(rate):>8.3f} | {np.mean(sil):>7.3f} | "
              f"{np.mean(frac):>13.4f} | {np.mean(acc):>7.3f} +- {np.std(acc):.3f} | "
              f"{np.mean(shuf):>9.3f} | {np.mean(notr):>13.3f} | "
              f"{'да' if healthy else 'НЕТ'}")

    print("\nЧТЕНИЕ ПО ОБЪЯВЛЕННОМУ ПРАВИЛУ:")
    good = [(c, a) for c, a, h in rows if h]
    if not good:
        print("  здоровых режимов нет -- результат не читается")
        return
    c, a = max(good, key=lambda x: x[1])
    print(f"  лучшая точность среди здоровых режимов: {a:.3f} при силе {c}")
    if a >= 0.65:
        print("  адресуемость ПОЯВЛЯЕТСЯ: немота объяснялась слабостью связи")
    else:
        print("  адресуемость НЕ появляется ни при какой здоровой силе:")
        print("  третья гипотеза тоже неверна, слабость связи немоту не объясняет")


if __name__ == "__main__":
    main()
