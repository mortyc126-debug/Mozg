"""v0.17: какой ПРОСТРАНСТВЕННЫЙ узор дают возникшие состояния.

v0.16 ввёл механизм дифференцировки: одинаковые элементы расходятся по
различимым состояниям (0.949 у краёв), расхождение требует соседей
(без них 0.057), и картина не считывается из геометрии (при другом шуме
согласие 0.470). Следующий пункт карты -- границы (Ф11).

НО граница требует ДОМЕНОВ: связных областей, где состояние одинаково, и
раздела между ними. Соперничество соседей даёт, вообще говоря, обратное:
узор "соль с перцем", где сосед именно НЕ такой. Косвенный признак уже
есть -- по контактам |s_i - s_j| выше перестановочного нуля (0.6055
против 0.5043 на 24 сидах из 24), то есть соседи РАЗЛИЧНЫ сильнее
случайного. Строить границы поверх такого узора бессмысленно.

Поэтому прежде механизма -- измерение: как различие состояний зависит от
РАССТОЯНИЯ. Меряется среднее |s_i - s_j| по парам в кольцах расстояний,
против перестановочного нуля (метки s перемешиваются по узлам, геометрия
та же). Нуль обязан быть плоским -- это его самопроверка.

ПРЕДСКАЗАНИЯ, объявлены до запуска:
  * если узор "соль с перцем": на малых расстояниях наблюдаемое ВЫШЕ
    нуля, на больших -- сходится к нулю. Тогда доменов нет, и для
    пункта 3 нужен другой баланс: соперничество должно действовать
    ДАЛЬШЕ, чем сходство, иначе области не сложатся;
  * если узор доменный: на малых расстояниях наблюдаемое НИЖЕ нуля.
    Тогда домены уже есть, и можно сразу вводить границу;
  * если наблюдаемое совпадает с нулём на всех расстояниях: узор
    случаен в пространстве, и состояние, хотя и возникло, никак не
    расположено -- это тоже результат, и он запрещает говорить о
    "областях".

Радиус роста контакта 0.25, поэтому кольцо 0..0.25 -- это ровно те пары,
между которыми связь возможна.
"""
import sys
import numpy as np

sys.path.insert(0, "code")
from sim_core import simulate

SEEDS = list(range(101, 125))
ETA = 0.2
EDGES = [0.0, 0.05, 0.10, 0.15, 0.20, 0.25, 0.35, 0.50, 1.50]
N_PERM = 200


def rings(pos, s, rng, n_perm=N_PERM):
    d = np.linalg.norm(pos[:, None, :] - pos[None, :, :], axis=2)
    iu = np.triu_indices(len(pos), 1)
    dd = d[iu]
    diff = np.abs(s[:, None] - s[None, :])[iu]
    obs, nul, nus, cnt = [], [], [], []
    perms = [rng.permutation(s) for _ in range(n_perm)]
    pdiffs = [np.abs(p[:, None] - p[None, :])[iu] for p in perms]
    for lo, hi in zip(EDGES[:-1], EDGES[1:]):
        m = (dd >= lo) & (dd < hi)
        cnt.append(int(m.sum()))
        if not m.any():
            obs.append(np.nan); nul.append(np.nan); nus.append(np.nan); continue
        obs.append(float(diff[m].mean()))
        vals = np.array([pd[m].mean() for pd in pdiffs])
        nul.append(float(vals.mean())); nus.append(float(vals.std()))
    return np.array(obs), np.array(nul), np.array(nus), np.array(cnt)


def main():
    rng = np.random.default_rng(777)
    O, Nl, Ns, C = [], [], [], []
    for seed in SEEDS:
        r = simulate(seed=seed, drive=1.175, gradual_growth=False,
                     differentiation=ETA)
        o, n, ns, c = rings(r["positions"], r["state_s"], rng)
        O.append(o); Nl.append(n); Ns.append(ns); C.append(c)
    O, Nl, Ns, C = map(np.array, (O, Nl, Ns, C))

    print(f"{len(SEEDS)} seed'ов, eta = {ETA}; радиус роста контакта 0.25\n")
    print(f"{'кольцо':>14} | {'пар':>7} | {'|si-sj| набл.':>13} | "
          f"{'нуль':>18} | {'набл./нуль':>11} | {'выше нуля':>11}")
    for k, (lo, hi) in enumerate(zip(EDGES[:-1], EDGES[1:])):
        o, n, ns = O[:, k], Nl[:, k], Ns[:, k]
        up = int(np.nansum(o > n))
        print(f"{lo:>5.2f}..{hi:<8.2f} | {C[:, k].mean():>7.0f} | "
              f"{np.nanmean(o):>13.4f} | {np.nanmean(n):>8.4f} +- {np.nanmean(ns):.4f} | "
              f"{np.nanmean(o) / np.nanmean(n):>11.4f} | {up:>4} из {len(SEEDS)}")

    # самопроверка нуля: он обязан быть плоским по кольцам
    flat = np.nanstd(np.nanmean(Nl, axis=0)) / np.nanmean(Nl)
    print(f"\nсамопроверка нуля: разброс по кольцам {flat * 100:.2f}% от среднего "
          f"({'плоский, как и обязан' if flat < 0.02 else 'НЕ ПЛОСКИЙ -- нуль негоден'})")

    near = np.nanmean(O[:, 0]) / np.nanmean(Nl[:, 0])
    far = np.nanmean(O[:, -1]) / np.nanmean(Nl[:, -1])
    print(f"\nЧТЕНИЕ: ближнее кольцо {near:.4f}, дальнее {far:.4f}")
    if near > 1.02:
        print("  узор СОЛЬ С ПЕРЦЕМ: соседи различны сильнее случайного, доменов нет.")
        print("  Для пункта 3 нужен другой баланс: соперничество ДАЛЬШЕ, чем сходство.")
    elif near < 0.98:
        print("  узор ДОМЕННЫЙ: соседи схожи сильнее случайного, области есть.")
    else:
        print("  узор СЛУЧАЕН в пространстве: состояние возникло, но никак не расположено.")


if __name__ == "__main__":
    main()
