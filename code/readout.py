"""Чтение состояния ткани: отделимость двух откликов.

Отдельный файл, а не копия в каждом измерении, -- нарочно. Урок №34:
мера, размноженная по файлам, расходится между ними незаметно.

ПОЧЕМУ НЕ "ВЫБРАСЫВАНИЕ ПО ОДНОЙ" (leave-one-out). Первая редакция
меры, стоявшая в v0.30, считала ближайший центр с выбрасыванием пробы по
одной. У этого способа есть систематический перекос, и в разреженных
данных он не малый, а полный: выброшенная проба удаляется из СВОЕГО
центра и не удаляется из чужого, поэтому свой центр смещается ОТ неё, а
чужой остаётся на месте. Когда отклики почти нулевые, это решает исход
целиком, и точность выходит ровно 0.000 -- не "около случайности", а
устойчиво наоборот.

Отпечаток тот же, что у ошибки №33 (тогда пары просачивались в проверку
и точность тоже вышла ровно 0.000). Ровный ноль -- не признак слабого
сигнала, а признак того, что проверка устроена неверно: слабый сигнал
даёт 0.5, а не 0.

ЗДЕСЬ: многократное разбиение пополам. Центры считаются по одной
половине проб, проверяются на другой; ни одна проба не участвует в
своём центре. Разбиение стратифицированное (поровну из каждого класса),
повторяется REPEATS раз, результаты усредняются.
"""
import numpy as np

REPEATS = 40


def separability(X, y, seed, repeats=REPEATS):
    """Доля верных на отложенной половине, ближайший центр.

    X -- (проб, узлов), y -- метки 0/1. Возвращает None, если какой-то
    класс пуст: тогда мерить нечего и подставлять 0.5 нельзя.
    """
    X = np.asarray(X, dtype=float); y = np.asarray(y)
    i0 = np.where(y == 0)[0]; i1 = np.where(y == 1)[0]
    if len(i0) < 2 or len(i1) < 2:
        return None
    rng = np.random.default_rng(seed)
    got = []
    for _ in range(repeats):
        tr, te = [], []
        for idx in (i0, i1):
            p = rng.permutation(idx)
            h = len(p) // 2
            tr.append(p[:h]); te.append(p[h:])
        c0 = X[tr[0]].mean(axis=0); c1 = X[tr[1]].mean(axis=0)
        for k, idx in enumerate(te):
            d0 = np.linalg.norm(X[idx] - c0, axis=1)
            d1 = np.linalg.norm(X[idx] - c1, axis=1)
            tie = d0 == d1
            pred = (d1 < d0).astype(int)
            # ничья решается жребием, а не всегда в одну сторону:
            # иначе при пустых откликах мера показывает не 0.5, а край
            if tie.any():
                pred[tie] = rng.integers(0, 2, size=int(tie.sum()))
            got.append((pred == k).astype(float))
    return float(np.concatenate(got).mean())
