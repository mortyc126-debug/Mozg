"""v0.37: ткань, построившая себя сама, против ткани, получившей
расположение готовым.

ОТКУДА ВОПРОС. Это единственный незакрытый пункт критерия зачатка --
"растит число элементов и меняет форму", -- и одновременно самая старая
претензия к проекту, записанная в STAGE_MAP: пункт 1 дорожной карты был
не просто не выполнен, а ОБОЙДЁН. Расположение выдавалось системе готовым
(`rng.uniform`), число элементов было константой. Для проекта, чья суть --
приход к сложному из простого, стартовое состояние было сложнее, чем
должно быть.

ЧТО ДОБАВЛЕНО В ДВИЖОК. `growth_by_division`: ткань начинается с ОДНОГО
элемента в середине и строит остальное делением. Дочерний элемент садится
не в случайную сторону, а туда, где СВОБОДНЕЕ (из восьми проб выбирается
наименее тесная, слишком тесная отвергается вовсе) -- отсюда ткань растёт
наружу и обретает форму. Тождество при выключенном росте: 9 из 9.

Измерено при калибровке: при `div_rate` 0.25 ткань выходит на полную
численность (80) к 7.9 с, средняя степень 12.4, ближайший сосед 0.095 при
заданном шаге деления 0.10, радиус ткани 0.36.

ВОПРОС ЗДЕСЬ. Отличается ли ВЫРОСШЕЕ расположение от выданного готовым --
не на глаз, а по тому, сколько из ткани можно прочесть.

Вопрос уже задавался в v0.14 и получил ответ "нет". Но тогда (а) не было
настоящего роста, (б) мера была вчетверо грубее (урок №42), (в) не было
задачи на отделимость. Поэтому спрашивается заново.

СРАВНЕНИЕ ЧЕСТНОЕ ПО ПЛОЩАДИ И ПЛОТНОСТИ. Выросшая ткань занимает круг,
а не весь квадрат. Поэтому ткань сравнения рассыпается СЛУЧАЙНО В ТОМ ЖЕ
КРУГЕ, с тем же числом элементов: совпадают и площадь, и численность, и,
как следствие, плотность. Отличается только РАСПОЛОЖЕНИЕ -- выросло оно
или брошено жребием. Это и есть спутывающий фактор, выравненный по той
величине, через которую он входит в модель (урок №30).

ЗАДАЧА -- та же, что в v0.31-v0.36: два перемежённых образа на краю
ткани, читается отклик остальных узлов. Воздействия ВО ВРЕМЯ РАЗВИТИЯ
здесь нет ни у кого: спрашивается про расположение, а не про обучение.

ПРАВИЛО ЧТЕНИЯ, объявлено до запуска:
  * проверка плотности ИСПОЛНЯЕМАЯ: при расхождении средней степени
    больше 10% вердикт не выносится (уроки №30, №37);
  * оба края промежутка стерегутся: если обе точности ниже 0.52 или обе
    выше 0.85, вердикта нет (ошибка №39);
  * перемешанные метки 0.42-0.58 (ошибка №40);
  * шум меры измерен и равен 2.04 п.п. при 320 пробах; поэтому разница
    меньше 2 п.п. НЕ ЧИТАЕТСЯ как эффект, даже если знак устойчив
    (урок №42). Это объявляется ДО, а не после;
  * доля сидов с биномиальным p и величина в п.п. -- всегда рядом.
"""
import sys

import numpy as np

sys.path.insert(0, "code")
import v31_learned_readability as v31
from sim_core import simulate

N = v31.N
SEEDS = list(range(3101, 3141))
MIN_EFFECT = 0.02          # ниже -- не читается (шум меры 2.04 п.п.)

GROWN = dict(drive=0.8, homeostasis=False, gradual_growth=False,
             coupling=v31.COUPLING, contact_radius=0.25,
             growth_by_division=True, div_rate=0.25, div_crowd=7)


def scattered_like(pos, n, seed):
    """Те же n элементов, случайно, в том же круге."""
    c = pos.mean(axis=0)
    rad = float(np.max(np.linalg.norm(pos - c, axis=1)))
    rng = np.random.default_rng(seed + 909)
    out = np.empty((n, 2))
    k = 0
    while k < n:
        p = c + rad * (2.0 * rng.random(2) - 1.0)
        if np.linalg.norm(p - c) <= rad and np.all((p >= 0) & (p <= 1)):
            out[k] = p
            k += 1
    return out


def main():
    res = {c: {"acc": [], "nul": [], "deg": [], "frac": [], "n": []}
           for c in ("ВЫРОСШАЯ", "БРОШЕННАЯ ЖРЕБИЕМ")}
    paired = {c: [] for c in res}
    skipped = 0
    for seed in SEEDS:
        g = simulate(seed=seed, **GROWN)
        n = g["born"]
        if n < N:                      # неполная ткань в счёт не идёт
            skipped += 1
            continue
        pos = g["positions"][:n]
        base = dict(GROWN); base.pop("growth_by_division")
        base.pop("div_rate"); base.pop("div_crowd")
        r = simulate(seed=seed, positions=scattered_like(pos, N, seed), **base)
        row = {}
        for name, net in (("ВЫРОСШАЯ", g), ("БРОШЕННАЯ ЖРЕБИЕМ", r)):
            p1, p2, surf = v31.interleaved(net["positions"])
            read = np.setdiff1d(np.arange(N), surf)
            C = net["contacts"] | net["contacts"].T
            f, a, nl = v31.measure(net, p1, p2, read, seed + 77)
            res[name]["deg"].append(float(C.sum(axis=1).mean()))
            res[name]["frac"].append(f)
            res[name]["acc"].append(a); res[name]["nul"].append(nl)
            res[name]["n"].append(int(n))
            row[name] = a
        if any(v is None for v in row.values()):
            skipped += 1
        else:
            for c in res:
                paired[c].append(row[c])

    m = len(paired["ВЫРОСШАЯ"])
    print(f"{len(SEEDS)} сидов ({m} в счёт, {skipped} отброшено), "
          f"воздействия при развитии нет ни у кого\n")
    print(f"{'ткань':<20} | {'соседей':>7} | {'отклик':>7} | "
          f"{'точность':>8} | {'перемешано':>10}")
    for c in res:
        acc = [a for a in res[c]["acc"] if a is not None]
        nul = [a for a in res[c]["nul"] if a is not None]
        print(f"{c:<20} | {np.mean(res[c]['deg']):7.2f} | "
              f"{np.mean(res[c]['frac']):7.3f} | "
              f"{(np.mean(acc) if acc else float('nan')):8.3f} | "
              f"{(np.mean(nul) if nul else float('nan')):10.3f}")
    if m == 0:
        print("\n  мерить не на чем")
        return
    dg = np.mean(res["ВЫРОСШАЯ"]["deg"]); dr = np.mean(res["БРОШЕННАЯ ЖРЕБИЕМ"]["deg"])
    mism = abs(dg - dr) / dr
    print(f"\nплотность: {dg:.2f} против {dr:.2f}, расхождение {mism*100:.2f}% "
          f"(порог 10%)")
    a = np.array(paired["ВЫРОСШАЯ"]); b = np.array(paired["БРОШЕННАЯ ЖРЕБИЕМ"])
    nul_all = np.mean([x for c in res for x in res[c]["nul"] if x is not None])
    k = int((a > b).sum())
    p = v31.p_ge(k, m)
    print(f"\nЧТЕНИЕ ({m} сидов):")
    print(f"  выросшая выше брошенной: {k} из {m}, p = {p:.4f} "
          f"({b.mean():.3f} -> {a.mean():.3f}, {(a - b).mean()*100:+.2f} п.п.)")
    if mism > 0.10:
        print("  ПЛОТНОСТЬ НЕ ВЫРАВНЕНА -- вердикт не выносится")
    elif not (0.42 <= nul_all <= 0.58):
        print(f"  перемешанные метки {nul_all:.3f} -- мера неисправна")
    elif max(a.mean(), b.mean()) < 0.52 or min(a.mean(), b.mean()) > 0.85:
        print("  пол или потолок -- вердикт не выносится")
    elif abs((a - b).mean()) < MIN_EFFECT:
        print(f"  разница меньше объявленного порога {MIN_EFFECT*100:.0f} п.п. "
              "(шум меры) -- РАСПОЛОЖЕНИЕ НЕ ЧИТАЕТСЯ КАК ЭФФЕКТ, "
              "сколь бы устойчив ни был знак")
    elif p < 0.05:
        print("  ВЫРОСШЕЕ РАСПОЛОЖЕНИЕ ЧИТАЕТСЯ ЛУЧШЕ БРОШЕННОГО ЖРЕБИЕМ")
    else:
        print("  разница есть по величине, но не по знаку -- читать осторожно")


if __name__ == "__main__":
    main()
