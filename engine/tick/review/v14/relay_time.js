// Доля времени, когда канал 9 заметно выше потолка без передатчика, и самый длинный такой отрезок.
// Потолки посчитаны в deep_theory.js: на одних датчиках 0.36 (глубина 1) и 0.24 (глубина 2);
// с памятью на один круг, то есть с прямой покупкой товара источника 8 и без всякого посредника,
// на глубине 2 доступно те же 0.36. Порог 0.6 стоит выше всех трёх.
const M = require('./neuron2.js');
const seed = +process.argv[2], w = M.create(seed);
let on = 0, n = 0, run = 0, best = 0;
for (let r = 1; r <= 100000; r++) {
  M.round(w);
  if (r % 500 === 0) {
    const s = M.stats(w); n++;
    if (s.alive && s.bits9 > 0.6) { on++; run += 500; best = Math.max(best, run); } else run = 0;
  }
}
console.log(`сид ${seed}: передатчик работает ${on}/${n} замеров (${(Math.floor(1000 * on / n) / 10).toFixed(1)}%), самый длинный отрезок ${best} кругов`);
