"""v0.46: замкнутая петля -- меняет ли ткань то, ЧТО ОНА ПОЛУЧАЕТ, и
меняется ли она сама оттого, что может.

ОТКУДА. Пункт 11 карты -- "обучается взаимодействовать со средой" -- до
сих пор не имел ПРЕДМЕТА: воздействие приходило, но ничего не зависело от
ответа ткани. Замыкание петли -- наименьшее, что делает его осмысленным.

МИР. Состояние u в [0,1] -- высота, на которой мир касается ткани. Образ
подаётся узлам с x < 0.42 и |y - u| < 0.06. Ткань действует на мир
разрядами дальних узлов (x > 0.60): верхние тянут u вверх, нижние вниз.
Есть постоянный снос вверх, так что бездействие имеет последствия.

ПЕРЕДАЧУ ПРИШЛОСЬ ПОДНЯТЬ, и это измерено, а не подобрано. При связи 10
(режим всех прошлых версий) сигнал до двигательных узлов НЕ ДОХОДИТ: за
24 секунды они дают 0.4 и 1.8 разряда, петля мертва. Это та же стена, что
в v0.30: в молчащей подложке сигнал не путешествует. При связи 14
отвечает 37% узлов, двигательные дают 31 и 71 разряд -- петля жива. Окно
связи 12-16 было найдено ещё в v0.21 ("отклик расширяется"), здесь оно и
понадобилось.

ЧТО ИЗМЕРЕНО ПРИ КАЛИБРОВКЕ: ткань ДЕЙСТВИТЕЛЬНО СДВИГАЕТ МИР. Средний u
при разомкнутой петле 0.740, при замкнутой 0.679 (связь 14) и 0.640
(связь 16). Нижняя двигательная область активнее верхней, и ткань тянет
мир вниз против сноса.

ГЛАВНЫЙ ВОПРОС ЗДЕСЬ ДРУГОЙ: меняется ли САМА ТКАНЬ оттого, что петля
замкнута? Для этого нужен контроль, который даёт ТУ ЖЕ историю входа без
влияния на неё.

  ЗАМКНУТО   -- мир отвечает на разряды ткани;
  ПРИВЯЗАНО  -- той же ткани (тот же сид, те же позиции, тот же поток
                случайных чисел) проигрывается ЗАПИСЬ u(t), снятая с
                замкнутого прогона. Вход тот же до мелочей, но ткань на
                него не влияет.

Это классическая привязка (yoked control): различие сводится к ОДНОЙ
вещи -- есть ли причинная связь между тем, что ткань делает, и тем, что
получает. Всё остальное совпадает.

ПРЕДСКАЗАНИЕ: в замкнутой петле собственная активность ткани ПРЕДШЕСТВУЕТ
сдвигу входа, то есть между её действием и её ощущением есть совпадение
во времени. Пластичность опирается именно на совпадение (v0.31, v0.36,
v0.44), значит замкнутая ткань должна читаться лучше привязанной.

ЗАДАЧА ЧТЕНИЯ: касание на высоте 0.3 против 0.7; читается отклик ДАЛЬНИХ
узлов (x > 0.55), которых касание не трогает. Геометрия помогает обоим
условиям ОДИНАКОВО, поэтому сравнение честное.

ПРАВИЛО ЧТЕНИЯ, объявлено до запуска:
  * порог 2 п.п. (шум меры, урок №42); доля сидов с биномиальным p;
  * оба края: если контроль вне 0.52-0.85, вердикт не выносится (№39);
  * перемешанные метки 0.42-0.58 (№40);
  * ОБЯЗАТЕЛЬНАЯ ПРОВЕРКА: записанный u(t) у привязанной ткани обязан
    совпасть с замкнутым до 1e-9. Если нет -- проигрывание неверно, и
    сравнивается не то;
  * сообщается также, насколько ткань сдвинула мир, -- без этого
    неизвестно, была ли петля вообще замкнута.
"""
import sys

import numpy as np

sys.path.insert(0, "code")
import v31_learned_readability as v31
import v37_self_built as v37
from sim_core import simulate

N = v31.N
SEEDS = list(range(5401, 5441))
DUR, RATE, COUP, GAIN, DRIFT = 24.0, 0.10, 14.0, 8.0, 0.02
XCUT, HALF, XFAR = 0.42, 0.06, 0.55
MIN_EFFECT = 0.02

BASE = {k: v for k, v in v37.GROWN.items()
        if k not in ("div_rate", "coupling")}


def touch(pos, u):
    return (pos[:, 0] < XCUT) & (np.abs(pos[:, 1] - u) < HALF)


def live_world(u, fired, pos, dt):
    far = pos[:, 0] > 0.60
    up = float(np.sum(fired & far & (pos[:, 1] > 0.65)))
    dn = float(np.sum(fired & far & (pos[:, 1] < 0.35)))
    u = u + GAIN * (up - dn) * dt + DRIFT * dt
    if u > 1.0:
        u = 2.0 - u
    if u < 0.0:
        u = -u
    return min(max(u, 0.0), 1.0)


def replay_world(trace, dt):
    """Проигрывает записанный мир, не глядя на ткань."""
    t_rec, u_rec = trace[:, 0], trace[:, 1]
    box = {"k": 0}

    def w(u, fired, pos, _dt):
        t = box["k"] * dt
        box["k"] += 1
        i = min(int(np.searchsorted(t_rec, t, side="right")) - 1,
                len(u_rec) - 1)
        return float(u_rec[max(i, 0)])
    return w


def grow(seed, world, init=0.5):
    return simulate(seed=seed, stimulus=[touch], stimulus_amp=0.4,
                    stimulus_period=0.2, duration=DUR, div_rate=RATE,
                    coupling=COUP, world=world, world_init=init,
                    activity_memory=0.05, **BASE)


def main():
    res = {c: {"acc": [], "nul": [], "frac": [], "u": [], "deg": []}
           for c in ("ЗАМКНУТО", "ПРИВЯЗАНО")}
    mism = []
    skipped = 0
    for seed in SEEDS:
        a = grow(seed, live_world)
        if a["born"] < N or len(a["world"]) == 0:
            skipped += 1
            continue
        b = grow(seed, replay_world(a["world"], 0.001))
        if b["born"] < N:
            skipped += 1
            continue
        mism.append(float(np.max(np.abs(a["world"][:, 1] - b["world"][:, 1]))))
        row = {}
        for name, net in (("ЗАМКНУТО", a), ("ПРИВЯЗАНО", b)):
            pos = net["positions"]
            p1 = np.where(touch(pos, 0.3))[0]
            p2 = np.where(touch(pos, 0.7))[0]
            read = np.where(pos[:, 0] > XFAR)[0]
            if len(p1) < 3 or len(p2) < 3 or len(read) < 10:
                row[name] = None
                continue
            C = net["contacts"] | net["contacts"].T
            f, ac, nl = v31.measure(net, p1, p2, read, seed + 77)
            row[name] = (f, ac, nl, float(net["world"][:, 1].mean()),
                         float(C.sum(axis=1).mean()))
        if any(v is None or v[1] is None for v in row.values()):
            skipped += 1
            continue
        for name, (f, ac, nl, u, deg) in row.items():
            res[name]["frac"].append(f); res[name]["acc"].append(ac)
            res[name]["nul"].append(nl); res[name]["u"].append(u)
            res[name]["deg"].append(deg)

    n = len(res["ЗАМКНУТО"]["acc"])
    print(f"{len(SEEDS)} сидов ({n} в счёт, {skipped} отброшено); "
          f"развитие {DUR:.0f} с, связь {COUP:g}, усиление {GAIN:g}\n")
    if n == 0:
        print("  мерить не на чем")
        return
    print(f"{'условие':<11} | {'соседей':>7} | {'средний u':>9} | {'отклик':>7} | "
          f"{'точность':>8} | {'перемеш.':>8}")
    for c in res:
        r = res[c]
        print(f"{c:<11} | {np.mean(r['deg']):7.2f} | {np.mean(r['u']):9.3f} | "
              f"{np.mean(r['frac']):7.3f} | {np.mean(r['acc']):8.3f} | "
              f"{np.mean(r['nul']):8.3f}")
    a = np.array(res["ЗАМКНУТО"]["acc"]); b = np.array(res["ПРИВЯЗАНО"]["acc"])
    nul_all = np.mean(res["ЗАМКНУТО"]["nul"] + res["ПРИВЯЗАНО"]["nul"])
    k = int((a > b).sum()); p = v31.p_ge(k, n)
    print(f"\nпроверки: проигрывание расходится с записью на "
          f"{np.max(mism):.2e} (порог 1e-9); перемешанные метки {nul_all:.3f}")
    print(f"\nЧТЕНИЕ ({n} сидов):")
    print(f"  замкнутая выше привязанной: {k} из {n}, p = {p:.4f} "
          f"({b.mean():.3f} -> {a.mean():.3f}, {(a - b).mean() * 100:+.2f} п.п.)")
    if np.max(mism) > 1e-9:
        print("  ПРОИГРЫВАНИЕ НЕВЕРНО -- сравнивается не то, вердикт не выносится")
    elif not (0.42 <= nul_all <= 0.58):
        print(f"  перемешанные метки {nul_all:.3f} -- мера неисправна")
    elif not (0.52 <= b.mean() <= 0.85):
        print(f"  контроль {b.mean():.3f} вне 0.52-0.85 -- вердикт не выносится")
    elif abs((a - b).mean()) < MIN_EFFECT:
        print(f"  разница меньше порога {MIN_EFFECT * 100:.0f} п.п. -- "
              "замыкание петли на читаемость не влияет")
    elif p < 0.05:
        print("  ЗАМЫКАНИЕ ПЕТЛИ МЕНЯЕТ ТКАНЬ: та же история входа без "
              "влияния на него даёт меньше")
    else:
        print("  величина выше порога, но знак неустойчив")


if __name__ == "__main__":
    main()
