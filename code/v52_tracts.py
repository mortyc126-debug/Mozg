"""v0.52: ТРАКТЫ -- заменяют ли пути подпорку, которой оживляли петлю.

ОТКУДА. v0.46 замкнул петлю, но она была мертва: сигнал не доходил от
сенсорной поверхности до двигательной области (0.4 и 1.8 разряда за 24
секунды). Оживили грубо -- подняв силу связи с 10 до 14, то есть заставив
возбуждение расползаться по всей ткани разом. Это подпорка, а не решение:
она сменила режим по сравнению со всеми версиями 0.21-0.45.

ПУТЬ К ЭТОЙ ВЕРСИИ ШЁЛ ЧЕРЕЗ ДВЕ ОШИБКИ, обе записаны:

  1. "Ткань местная, поэтому сигнал не ходит" -- верно наполовину.
     Добавил дальние связи; при силе 10 петля НЕ ОЖИЛА вовсе (0.2
     разряда против 0.8 без них). Одна связь слишком слаба, чтобы
     передать разряд: при силе 10 даёт 0.15 при нужных 0.2. Расстояние
     ни при чём.
  2. "Значит нужна толщина" -- тоже наполовину. Пучки подняли отклик до
     6.0, но толщина дошла лишь до 2.3 связи на пару мест, а v0.29
     измерил, что мостик несёт след начиная примерно с 7.5.

РЕШИЛОСЬ ПЕРЕСМОТРОМ УМОЛЧАНИЯ, А НЕ МЕХАНИЗМА. У всех связей был
одинаковый начальный вес 0.015 -- это никем не выбиралось, так досталось
от биологического образца. По PRINCIPLES §2-бис ("сходство с образцом не
довод") умолчание пересмотрено: дальнему пути разрешено нести больше на
волокно.

КАЛИБРОВКА (12 тканей, сила связи 10):

    дальних/шаг | вес дальней | двиг. разрядов | немых
            0.0 |          -- |            0.8 | 11 из 12
            3.0 |       0.015 |            6.0 |  9 из 12
            3.0 |       0.025 |            8.2 |  8 из 12
            3.0 |       0.040 |           23.4 |  8 из 12
            3.0 |       0.080 |           87.2 |  5 из 12
            1.0 |       0.080 |            2.0 | 11 из 12

Последняя строка важнее прочих: тот же вес, но втрое меньше дальних
связей -- и петля снова мертва. Нужны И ТОЛЩИНА, И СИЛА; ни пучок из
немощных волокон, ни одинокое сильное волокно пути не делают.

ПРАВИЛО ЧТЕНИЯ, объявлено до запуска:
  * ГЛАВНОЕ: доля тканей с ДЕЙСТВУЮЩЕЙ петлёй (хотя бы один двигательный
    разряд) при связи 10 С ТРАКТАМИ должна быть не ниже, чем при связи 14
    БЕЗ трактов. Это и есть "форма заменила подпорку";
  * ОБЯЗАТЕЛЬНАЯ ПРОВЕРКА, отличающая ПУТЬ от РАЗГОНА: доля отвечающих
    узлов у ткани с трактами НЕ ДОЛЖНА превышать ту, что даёт связь 14.
    Если превышает -- значит мы не провели сигнал по пути, а просто
    сделали всю ткань громче, то есть подменили подпорку другой
    подпоркой, и вердикт не выносится;
  * сообщается также, сколько всего разрядов: путь обязан доставлять
    сигнал ДЕШЕВЛЕ разгона, а не дороже;
  * сиды свежие (6501-6560).
"""
import sys

import numpy as np

sys.path.insert(0, "code")
import v31_learned_readability as v31
import v37_self_built as v37
import v46_closed_loop as v46
from sim_core import simulate

N = v31.N
SEEDS = list(range(6501, 6561))
BASE = {k: v for k, v in v37.GROWN.items()
        if k not in ("div_rate", "coupling")}

CONDS = {
    "СВЯЗЬ 10, БЕЗ ТРАКТОВ": dict(coupling=10.0, long_range_rate=0.0),
    "СВЯЗЬ 14, ПОДПОРКА":    dict(coupling=14.0, long_range_rate=0.0),
    "СВЯЗЬ 10, ТРАКТЫ":      dict(coupling=10.0, long_range_rate=3.0,
                                  bundle_bias=0.8, long_range_weight=0.08),
}


def run(seed, kw):
    return simulate(seed=seed, stimulus=[v46.touch], stimulus_amp=0.4,
                    stimulus_period=0.2, duration=24.0, div_rate=0.10,
                    world=v46.live_world, world_init=0.5,
                    activity_memory=0.05, **kw, **BASE)


def main():
    res = {c: {"motor": [], "spikes": [], "resp": [], "live": [], "lr": []}
           for c in CONDS}
    n = 0
    for seed in SEEDS:
        row = {}
        for name, kw in CONDS.items():
            r = run(seed, kw)
            pos, sk = r["positions"], r["spikes"]
            alive = np.isfinite(r["birth"])
            far = alive & (pos[:, 0] > 0.60)
            m = int(sk[:, far & (pos[:, 1] > 0.65)].sum()
                    + sk[:, far & (pos[:, 1] < 0.35)].sum())
            D = np.linalg.norm(pos[:, None, :] - pos[None, :, :], axis=2)
            lr = int((r["contacts"] & (D > 0.25)
                      & alive[:, None] & alive[None, :]).sum())
            row[name] = (m, int(sk.sum()),
                         float((sk[:, alive].sum(axis=0) > 0).mean()), lr)
        n += 1
        for name, (m, sp, rp, lr) in row.items():
            res[name]["motor"].append(m); res[name]["spikes"].append(sp)
            res[name]["resp"].append(rp); res[name]["live"].append(int(m > 0))
            res[name]["lr"].append(lr)

    print(f"{n} свежих сидов\n")
    print(f"{'условие':<23} | {'дальних':>7} | {'двиг. разрядов':>14} | "
          f"{'всего разрядов':>14} | {'отвечало узлов':>14} | {'петля жива':>10}")
    for c in CONDS:
        r = res[c]
        print(f"{c:<23} | {np.mean(r['lr']):7.1f} | {np.mean(r['motor']):14.1f} | "
              f"{np.mean(r['spikes']):14.1f} | {np.mean(r['resp']):14.3f} | "
              f"{np.mean(r['live']) * 100:9.0f}%")

    a = res["СВЯЗЬ 10, ТРАКТЫ"]; b = res["СВЯЗЬ 14, ПОДПОРКА"]
    c0 = res["СВЯЗЬ 10, БЕЗ ТРАКТОВ"]
    live_a, live_b = np.mean(a["live"]), np.mean(b["live"])
    resp_a, resp_b = np.mean(a["resp"]), np.mean(b["resp"])
    k = int((np.array(a["motor"]) > np.array(c0["motor"])).sum())
    print(f"\nЧТЕНИЕ ({n} сидов):")
    print(f"  петля жива: {live_a * 100:.0f}% с трактами против "
          f"{live_b * 100:.0f}% на подпорке и "
          f"{np.mean(c0['live']) * 100:.0f}% без того и другого")
    print(f"  тракты выше своего контроля по разрядам: {k} из {n}, "
          f"p = {v31.p_ge(k, n):.4f}")
    print(f"  отвечало узлов: {resp_a:.3f} с трактами против {resp_b:.3f} "
          f"на подпорке (путь не должен быть громче разгона)")
    print(f"  всего разрядов: {np.mean(a['spikes']):.0f} против "
          f"{np.mean(b['spikes']):.0f}")
    if resp_a > resp_b:
        print("\n  ЭТО НЕ ПУТЬ, А РАЗГОН: ткань с трактами шумит шире, чем на "
              "подпорке. Подпорка подменена другой подпоркой, вердикта нет")
    elif live_a >= live_b:
        print("\n  ФОРМА ЗАМЕНИЛА ПОДПОРКУ: при обычной силе связи петля жива "
              "не реже, чем при поднятой, и ткань при этом не шумнее")
    else:
        print("\n  тракты петлю оживляют, но реже подпорки -- замены нет")


if __name__ == "__main__":
    main()
