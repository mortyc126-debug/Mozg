"""v0.18: становится ли узор ГРАНИЦЕЙ, то есть структурным разрывом.

v0.16 дал механизм: одинаковые элементы расходятся по состояниям.
v0.17 показал, что состояния складываются в ДОМЕНЫ с масштабом,
задаваемым дальностью правила. Но состояние ни на что не влияло --
домены были узором поверх сети, а не её устройством.

Здесь состояние получает следствие (пункт 3 карты, Ф11): различие
состояний МЕШАЕТ связи вырасти,
    вероятность роста контакта = 0.15 * (1 - affinity*|s_i - s_j|).
При affinity = 1 противоположные узлы не связываются вовсе. Тогда там,
где сходятся области, должен возникнуть структурный разрыв -- граница.

ТАВТОЛОГИЯ НАЗВАНА ЗАРАНЕЕ. Что доля контактов между НЕПОХОЖИМИ узлами
упадёт -- следствие самого правила, а не открытие. Она выводится, но
выводом не считается. Проверяемое утверждение другое: становится ли от
этого правила САМ УЗОР отчётливее и меняется ли работа сети.

ПЛОТНОСТЬ ВЫРАВНЕНА (урок №30). Правило режет часть контактов: при
радиусе 0.25 средняя степень падает с 12.375 до 10.983, то есть на
11.25%. Радиус для условия с притяжением подобран отдельной калибровкой
на 8 seed'ах: 0.2656. Остаточное расхождение выводится ОТДЕЛЬНОЙ СТРОКОЙ
до обсуждения результата; при расхождении выше 10% сравнение не читается.
Невыравненное условие тоже прогоняется -- чтобы видеть, что сказала бы
ловушка №13.

УСЛОВИЯ, 24 СВЕЖИХ seed'а (201..224; прежние 11..22 и 101..124 не
используются -- уроки №27, №28). Во всех элементы одинаковы: drive 1.175,
появление одновременное, дифференцировка 0.2.

МЕРЫ.
1. ТАВТОЛОГИЧЕСКАЯ: доля контактов между непохожими (|s_i-s_j| > 0.5).
2. ОТЧЁТЛИВОСТЬ УЗОРА: профиль |s_i - s_j| по кольцам расстояний против
   перестановочного нуля, как в v0.17. Если граница складывается, ближнее
   кольцо обязано стать ГЛУБЖЕ (соседи ещё более схожи), а кольцо
   максимума -- выше.
3. ФУНКЦИОНАЛЬНОЕ СЛЕДСТВИЕ: согласование активности (мера v0.3, нуль
   циклического сдвига). Разрыв между областями обязан менять то, КАК
   сеть согласуется. Это и есть проверка, что граница -- устройство,
   а не картинка.

ПРАВИЛО ЧТЕНИЯ, объявлено до запуска:
  * граница как структура установлена, если остаточное расхождение по
    числу соседей не выше 10% И ближнее кольцо профиля углубляется не
    менее чем на 5/6 seed'ов;
  * функциональное следствие установлено, если согласование отличается
    от контроля в одну сторону не менее чем на 5/6 seed'ов ПРИ
    ВЫРАВНЕННОЙ ПЛОТНОСТИ;
  * если согласование отличается только в НЕВЫРАВНЕННОМ условии --
    отличие даёт плотность, а не граница (ловушка №13), и так и
    записывается;
  * если узор не углубляется -- правило режет связи, но границы не
    образует, и Ф11 остаётся невыполненным.

ВТОРАЯ РЕДАКЦИЯ. Первая шла при eta = 0.2 и дала пустой результат: доля
связей между непохожими почти не изменилась (0.6028 -> 0.5934). Причина
найдена измерением, а не догадкой -- линии времени не совпадают:

    время | контактов сложилось | состояний разошлось
     1.0с |         29%         |          9%
     2.0с |         61%         |         15%
     4.0с |         87%         |         45%
     6.0с |         96%         |         86%

К моменту, когда состояния разошлись, связи уже стояли, и правило
действовало на последние 4% контактов. Это не провал замысла, а порядок
событий: разметка обязана опережать проводку.

При eta = 0.5 порядок верный: к моменту, когда сложилась половина связей,
у краёв уже 68% узлов (при 0.2 было 11%). Батарея v0.16 перепроверена на
этой скорости на свежих seed'ах 301..324 и прошла все четыре условия:
края 0.980, без соседей 0.118 (12% от основного), |si-sj| выше нуля
24 из 24, при другом шуме согласие 0.501. Плотность перекалибрована:
радиус 0.285.
"""
import sys
import numpy as np

sys.path.insert(0, "code")
from sim_core import simulate
from v03_cyclic_shift import cyclic_shift_control

import os
SEEDS = [int(x) for x in os.environ.get("SEEDS", ",".join(map(str, range(401, 425)))).split(",")]
ETA = float(os.environ.get("ETA", 0.5))
RAD_REF = 0.25
RAD_MATCHED = float(os.environ.get("RAD", 0.285))   # из калибровки на 8 seed'ах
EDGES = [0.0, 0.05, 0.10, 0.15, 0.20, 0.25, 0.35, 0.50, 1.50]
N_PERM = 100


def ring_profile(pos, s, rng):
    d = np.linalg.norm(pos[:, None, :] - pos[None, :, :], axis=2)
    iu = np.triu_indices(len(pos), 1)
    dd, diff = d[iu], np.abs(s[:, None] - s[None, :])[iu]
    pd = [np.abs(p[:, None] - p[None, :])[iu]
          for p in (rng.permutation(s) for _ in range(N_PERM))]
    out = []
    for lo, hi in zip(EDGES[:-1], EDGES[1:]):
        m = (dd >= lo) & (dd < hi)
        if m.sum() < 5:
            out.append(np.nan); continue
        nul = np.mean([x[m].mean() for x in pd])
        out.append(diff[m].mean() / nul if nul > 0 else np.nan)
    return np.array(out)


def unlike_fraction(s, contacts):
    nb = np.triu(contacts | contacts.T, 1)
    ii, jj = np.nonzero(nb)
    if len(ii) == 0:
        return np.nan
    return float(np.mean(np.abs(s[ii] - s[jj]) > 0.5))


def main():
    conds = {
        "КОНТРОЛЬ": dict(state_affinity=0.0, contact_radius=RAD_REF),
        "ГРАНИЦА": dict(state_affinity=1.0, contact_radius=RAD_MATCHED),
        "ГРАНИЦА, не выравнено": dict(state_affinity=1.0, contact_radius=RAD_REF),
    }
    rng = np.random.default_rng(4242)
    acc = {c: {"deg": [], "unlike": [], "prof": [], "q": [], "rate": [],
               "silent": [], "edge": []} for c in conds}

    for seed in SEEDS:
        for name, kw in conds.items():
            r = simulate(seed=seed, drive=1.175, gradual_growth=False,
                         differentiation=ETA, **kw)
            s, C = r["state_s"], r["contacts"]
            acc[name]["deg"].append(float(C.sum(axis=1).mean()))
            acc[name]["unlike"].append(unlike_fraction(s, C))
            acc[name]["prof"].append(ring_profile(r["positions"], s, rng))
            q, _ = (lambda d: (d["q_ratio"], d["p_value"]))(
                cyclic_shift_control(r["spikes"], r["dt"], n_shuffles=100, seed=seed))
            acc[name]["q"].append(q)
            acc[name]["rate"].append(r["metrics"]["rate_hz"])
            acc[name]["silent"].append(r["metrics"]["silent_fraction"])
            acc[name]["edge"].append(float(np.mean((s < 0.1) | (s > 0.9))))

    ref_deg = np.mean(acc["КОНТРОЛЬ"]["deg"])
    print("ПРОВЕРКА ВЫРАВНИВАНИЯ (порог 10%), до обсуждения результата:")
    for c in conds:
        d = np.array(acc[c]["deg"])
        rel = abs(d.mean() - ref_deg) / ref_deg
        print(f"  {c:<22}: соседей {d.mean():6.3f}  расхождение {rel*100:5.2f}% "
              f"-- {'ЧИТАЕМО' if rel <= 0.10 else 'НЕ ЧИТАЕМО'}")

    print(f"\n{'условие':<22} | {'доля у краёв s':>14} | {'непохожих связей':>17} | "
          f"{'частота':>8} | {'согласование q':>15}")
    for c in conds:
        a = acc[c]
        print(f"{c:<22} | {np.mean(a['edge']):>14.3f} | {np.nanmean(a['unlike']):>17.4f} | "
              f"{np.mean(a['rate']):>8.3f} | {np.mean(a['q']):>7.4f} +- {np.std(a['q']):.4f}")
    print("  (доля непохожих связей -- следствие самого правила, не вывод)")

    print(f"\nПРОФИЛЬ УЗОРА (набл./нуль по кольцам):")
    print(f"{'условие':<22} | " + " | ".join(f"{lo:.2f}-{hi:.2f}"
          for lo, hi in zip(EDGES[:-1], EDGES[1:])))
    for c in conds:
        P = np.array(acc[c]["prof"], dtype=float)
        print(f"{c:<22} | " + " | ".join(f"{v:9.3f}" for v in np.nanmean(P, axis=0)))

    thr = int(np.ceil(len(SEEDS) * 5 / 6))
    pc = np.array(acc["КОНТРОЛЬ"]["prof"], dtype=float)
    pb = np.array(acc["ГРАНИЦА"]["prof"], dtype=float)
    deeper = int(np.nansum(pb[:, 0] < pc[:, 0]))
    qc = np.array(acc["КОНТРОЛЬ"]["q"])
    qb = np.array(acc["ГРАНИЦА"]["q"])
    qu = np.array(acc["ГРАНИЦА, не выравнено"]["q"])
    up_b = int((qb > qc).sum()); up_u = int((qu > qc).sum())

    print(f"\nЧТЕНИЕ ПО ОБЪЯВЛЕННОМУ ПРАВИЛУ (порог {thr} из {len(SEEDS)}):")
    print(f"  ближнее кольцо углубилось: {deeper} из {len(SEEDS)} "
          f"({np.nanmean(pc[:,0]):.3f} -> {np.nanmean(pb[:,0]):.3f}) -- "
          f"{'граница как структура ЕСТЬ' if deeper >= thr else 'НЕ ПОДТВЕРЖДЕНО'}")
    print(f"  согласование при выравненной плотности: {max(up_b, len(SEEDS)-up_b)} из {len(SEEDS)} "
          f"в одну сторону ({np.mean(qc):.4f} -> {np.mean(qb):.4f}) -- "
          f"{'функциональное следствие ЕСТЬ' if max(up_b, len(SEEDS)-up_b) >= thr else 'НЕ ПОДТВЕРЖДЕНО'}")
    print(f"  то же без выравнивания: {max(up_u, len(SEEDS)-up_u)} из {len(SEEDS)} "
          f"({np.mean(qc):.4f} -> {np.mean(qu):.4f}) -- для сравнения, что сказала бы ловушка №13")


if __name__ == "__main__":
    main()
