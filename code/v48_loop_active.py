"""v0.48: замкнутая петля против привязки -- на тканях, у которых петля
ДЕЙСТВИТЕЛЬНО замкнута.

ОТКУДА. v0.47 исправил три изъяна v0.46, и перевёрнутая проверка тут же
поймала четвёртый: у 8 сидов из 50 разряды замкнутой и привязанной ткани
совпали ПОБИТОВО. Вердикт не вынесен -- и правильно.

ПРИЧИНА ИЗМЕРЕНА. Двигательные области населены у всех тканей (9.8 узла
сверху, 10.3 снизу, пустых нет ни одной). Но у 12 тканей из 30 НЕТ НИ
ОДНОГО ДВИГАТЕЛЬНОГО РАЗРЯДА за все 24 секунды: ткань есть, выход есть,
а действия нет. У такой ткани мир движется одним сносом, и если донор
записи тоже оказался немым, обе записи совпадают -- и прогоны выходят
побитово одинаковыми.

То есть петля живёт не во всякой ткани: примерно в трёх из пяти. Это само
по себе стоит записать -- "замкнуть петлю" в этой модели не значит
"получить действующую ткань".

ЧТО ИСПРАВЛЕНО ЗДЕСЬ, и оба исправления разной природы:

  1. ДОНОР ЗАПИСИ выбирается только среди тканей, которые МИР ДВИГАЛИ.
     Это выбор по свойству ДОНОРА, а не той ткани, которую меряем, --
     значит на сравнение он не влияет. Тогда привязанная ткань всегда
     получает историю, которой сама бы не породила.
  2. В СЧЁТ идут ткани, у которых двигательные разряды есть В ОБОИХ
     условиях. Условие СИММЕТРИЧНО: оно не отбирает по исходу замкнутого
     прогона, а требует лишь, чтобы ткань вообще действовала. Число
     отброшенных сообщается.

ПРЕДСКАЗАНИЕ прежнее: в замкнутой петле собственная активность
предшествует сдвигу входа, между действием и ощущением возникает
совпадение во времени, а пластичность опирается именно на совпадение.

ПРАВИЛО ЧТЕНИЯ, объявлено до запуска:
  * порог 2 п.п. (урок №42), доля сидов с биномиальным p (урок №36);
  * оба края: контроль вне 0.52-0.85 -- вердикт не выносится (№39);
  * перемешанные метки 0.42-0.58 (№40);
  * перевёрнутая проверка остаётся: побитово совпавших условий обязано
    быть 0 (№48);
  * плотность связей между условиями не больше 10%;
  * СРЕДНЕЕ И ЗНАК читаются ВМЕСТЕ. В v0.47 они разошлись (среднее
    +0.76 п.п., но знак в пользу привязанной у 25 сидов из 37) -- верный
    признак, что среднее тянут немногие ткани. При расхождении знака и
    среднего вердикт не выносится, а сообщается расхождение.
"""
import sys

import numpy as np

sys.path.insert(0, "code")
import v31_learned_readability as v31
import v37_self_built as v37
import v46_closed_loop as v46
import v47_loop_yoked as v47
from sim_core import simulate

N = v31.N
SEEDS = list(range(5701, 5761))
MIN_EFFECT = 0.02


def motor_spikes(net):
    pos = net["positions"]
    alive = np.isfinite(net["birth"])
    far = alive & (pos[:, 0] > 0.60)
    up = far & (pos[:, 1] > 0.65)
    dn = far & (pos[:, 1] < 0.35)
    return int(net["spikes"][:, up].sum() + net["spikes"][:, dn].sum())


def main():
    closed, active = {}, []
    for seed in SEEDS:
        r = v47.run(seed, v46.live_world)
        if not len(r["world"]):
            continue
        closed[seed] = r
        if motor_spikes(r) > 0:
            active.append(seed)
    print(f"{len(SEEDS)} сидов: петля ДЕЙСТВУЕТ у {len(active)} "
          f"({len(active) / max(len(closed), 1) * 100:.0f}%)\n")
    if len(active) < 2:
        print("  действующих тканей слишком мало -- мерить не на чем")
        return

    res = {c: {"acc": [], "nul": [], "frac": [], "deg": [], "u": [], "mot": []}
           for c in ("ЗАМКНУТО", "ПРИВЯЗАНО")}
    same_spikes = 0
    no_motor = 0
    skipped = 0
    keys = sorted(closed)
    for i, seed in enumerate(keys):
        # донор -- только из действующих, и не сама ткань
        donors = [d for d in active if d != seed]
        donor = donors[i % len(donors)]
        a = closed[seed]
        b = v47.run(seed, v46.replay_world(closed[donor]["world"], 0.001))
        if np.array_equal(a["spikes"], b["spikes"]):
            same_spikes += 1
            continue
        if motor_spikes(a) == 0 or motor_spikes(b) == 0:
            no_motor += 1
            continue
        ra, rb = v47.read_net(a, seed), v47.read_net(b, seed)
        if ra is None or rb is None:
            skipped += 1
            continue
        for name, (f, ac, nl, deg), net in (("ЗАМКНУТО", ra, a),
                                            ("ПРИВЯЗАНО", rb, b)):
            res[name]["frac"].append(f); res[name]["acc"].append(ac)
            res[name]["nul"].append(nl); res[name]["deg"].append(deg)
            res[name]["u"].append(float(net["world"][:, 1].mean()))
            res[name]["mot"].append(motor_spikes(net))

    n = len(res["ЗАМКНУТО"]["acc"])
    print(f"{n} в счёт; {no_motor} без действия, {same_spikes} совпали "
          f"побитово, {skipped} без отклика\n")
    if n == 0:
        print("  мерить не на чем")
        return
    print(f"{'условие':<11} | {'соседей':>7} | {'средний u':>9} | "
          f"{'двиг. разрядов':>14} | {'отклик':>7} | {'точность':>8} | "
          f"{'перемеш.':>8}")
    for c in res:
        r = res[c]
        print(f"{c:<11} | {np.mean(r['deg']):7.2f} | {np.mean(r['u']):9.3f} | "
              f"{np.mean(r['mot']):14.1f} | {np.mean(r['frac']):7.3f} | "
              f"{np.mean(r['acc']):8.3f} | {np.mean(r['nul']):8.3f}")
    a = np.array(res["ЗАМКНУТО"]["acc"]); b = np.array(res["ПРИВЯЗАНО"]["acc"])
    nul_all = np.mean(res["ЗАМКНУТО"]["nul"] + res["ПРИВЯЗАНО"]["nul"])
    dg = np.mean(res["ЗАМКНУТО"]["deg"]); db = np.mean(res["ПРИВЯЗАНО"]["deg"])
    mism = abs(dg - db) / db
    k = int((a > b).sum()); p = v31.p_ge(k, n)
    d = (a - b).mean() * 100
    print(f"\nпроверки: побитово совпавших 0 (по построению отброшены); "
          f"плотность {mism * 100:.2f}%; перемешанные метки {nul_all:.3f}")
    print(f"\nЧТЕНИЕ ({n} сидов):")
    print(f"  замкнутая выше привязанной: {k} из {n}, p = {p:.4f} "
          f"({b.mean():.3f} -> {a.mean():.3f}, {d:+.2f} п.п.)")
    sign_agrees = (d > 0) == (k > n / 2)
    if mism > 0.10:
        print("  ПЛОТНОСТЬ НЕ ВЫРАВНЕНА -- вердикт не выносится")
    elif not (0.42 <= nul_all <= 0.58):
        print(f"  перемешанные метки {nul_all:.3f} -- мера неисправна")
    elif not (0.52 <= b.mean() <= 0.85):
        print(f"  контроль {b.mean():.3f} вне 0.52-0.85 -- вердикт не выносится")
    elif not sign_agrees:
        print("  СРЕДНЕЕ И ЗНАК РАСХОДЯТСЯ -- среднее тянут немногие ткани, "
              "вердикт не выносится")
    elif abs(d) < MIN_EFFECT * 100:
        print(f"  разница меньше порога {MIN_EFFECT * 100:.0f} п.п. -- "
              "замыкание петли на читаемость НЕ ВЛИЯЕТ")
    elif p < 0.05:
        print("  ЗАМЫКАНИЕ ПЕТЛИ МЕНЯЕТ ТКАНЬ")
    else:
        print("  величина выше порога, но знак неустойчив")


if __name__ == "__main__":
    main()
