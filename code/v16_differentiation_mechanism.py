"""v0.16: механизм дифференцировки -- расходятся ли ОДИНАКОВЫЕ элементы.

v0.15 показал, что различий, которые возникали бы сами, в модели нет:
81.9% разброса порога давал выданный drive, 12.9% -- собственный шум,
а взаимодействие 1.1% и лишь на 8 сидах из 12. Механизма дифференцировки
не было вовсе. Здесь он вводится и проверяется.

ФУНКЦИОНАЛЬНАЯ ПОСТАНОВКА (PRINCIPLES п.3). Что несёт дифференцировка:
возможность того, чтобы разные области делали РАЗНОЕ. Цифровой механизм
с тем же причинным следствием -- локальное соперничество: элемент мешает
соседям быть таким же, как он. Молекул здесь нет и не требуется.

ПРАВИЛО. У каждого узла величина s, у ВСЕХ ровно 0.5 в начале.
  ds = eta * s*(1-s) * ( own - 4*(pressure - 0.5) )
  own      -- собственная активность относительно средней по сети;
  pressure -- среднее s соседей по контактам (0.5, если соседей нет).
Множитель s(1-s) делает края устойчивыми, середину -- нет.

s НИ НА ЧТО НЕ ВЛИЯЕТ, и это выбор устройства проверки, а не недоделка.
При включённом механизме остальной прогон побитово тот же, что при
выключенном (проверено, 3 из 3), поэтому любая найденная картина
принадлежит механизму, а не его побочным следствиям. Функциональное
следствие -- отдельный следующий шаг, и пока его НЕТ.

УСЛОВИЯ. Во всех элементы ОДИНАКОВЫ: drive 1.175 у каждого, появление
одновременное. Иначе мерилось бы снова выданное различие.
  ВЫКЛ   -- механизм выключен (s обязана остаться ровно 0.5);
  ВКЛ    -- механизм включён, сеть обычная;
  БЕЗ ТОКА -- контакты есть (соперничество работает), но transmission=False:
             электрического взаимодействия нет;
  БЕЗ СОСЕДЕЙ -- радиус контакта мал, контактов нет вовсе: соперничать не
             с кем, остаётся только собственный член.
Сравнение ВКЛ с БЕЗ СОСЕДЕЙ отделяет соперничество от самоусиления;
сравнение БЕЗ ТОКА с БЕЗ СОСЕДЕЙ -- соперничество отдельно от электрики.

МЕРЫ.
1. Различимость: доля узлов у краёв (s < 0.1 или s > 0.9).
2. Устройство картины: среднее |s_i - s_j| по контактам против
   ПЕРЕСТАНОВОЧНОГО нуля (метки s перемешиваются по узлам, сеть та же,
   200 перестановок). Соперничество обязано разводить именно СОСЕДЕЙ,
   поэтому наблюдаемое должно быть ВЫШЕ нуля. Нуль проверяется на
   центрированность.
3. Не считывание геометрии: та же геометрия, другой шум (позиции и drive
   переданы явно и неизменны, меняется только seed). Доля узлов,
   получивших то же состояние в двух прогонах. Если близка к единице --
   картина задана геометрией, а не возникла.

ВТОРАЯ РЕДАКЦИЯ. Первая шла при eta = 0.05 и дала долю у краёв 0.144:
механизм не успевал за прогон. Развёртка по eta (12 seed'ов) показала
окно:

    eta   доля у краёв   разброс s   доля s>0.5   без соседей: края
   0.05          0.144      0.2561        0.493               0.001
   0.2           0.935      0.4863        0.502               0.047
   0.5           0.985      0.4962        0.508               0.139
   1.0           0.991      0.4976        0.508               0.454
   2.0           1.000      0.2975        0.109               1.000

При 2.0 расходятся и одиночки (контроль 1.000), а разделение вырождается
(0.109 вместо половины) -- слишком сильно. Рабочая полоса 0.2..0.5.
ЭТО ГИПОТЕЗА, ПОРОЖДЁННАЯ РАЗВЁРТКОЙ, и на тех же seed'ах она не
проверяется (уроки №27 и №28). Здесь взяты СВЕЖИЕ seed'ы, с прежними не
пересекающиеся, и eta = 0.2 -- нижний край полосы, а не лучшая точка.

Кроме того исправлено правило: "заметно меньшая доля у краёв" было
записано как абсолютный запас 0.15, который при доле 0.144 не мог быть
выполнен в принципе, и строка вывода напечатала неверный вердикт при
верных числах. Теперь сравнение ОТНОСИТЕЛЬНОЕ.

ПРАВИЛО ЧТЕНИЯ, объявлено до запуска:
  * дифференцировка установлена, если ВСЕ четыре: доля у краёв в ВКЛ не
    ниже 2/3; наблюдаемое |s_i - s_j| выше перестановочного нуля не менее
    чем на 5/6 seed'ов; БЕЗ СОСЕДЕЙ даёт не более ТРЕТИ от доли у краёв
    в ВКЛ; согласие при другом шуме заметно ниже единицы;
  * если БЕЗ СОСЕДЕЙ даёт ту же долю у краёв -- расхождение создаётся
    самоусилением собственного шума, а не соперничеством. Тогда
    записывается ИМЕННО ЭТО, и вклад соперничества оценивается только по
    мере 2 (устройство картины);
  * если наблюдаемое |s_i - s_j| не отличается от нуля -- картина
    случайна относительно сети, соперничества нет.
"""
import sys
import numpy as np

sys.path.insert(0, "code")
from sim_core import simulate

N = 80
SEEDS = list(range(101, 125))     # свежие, с прежними 11..22 не пересекаются
DRIVE = 1.175
ETA = float(sys.argv[1]) if len(sys.argv) > 1 else 0.2
EDGE = 0.1
N_PERM = 200


def edge_contrast(s, contacts, rng, n_perm=N_PERM):
    """Среднее |s_i - s_j| по контактам и перестановочный нуль."""
    nb = np.triu(contacts | contacts.T, 1)
    ii, jj = np.nonzero(nb)
    if len(ii) == 0:
        return np.nan, np.nan, np.nan
    obs = np.abs(s[ii] - s[jj]).mean()
    null = np.empty(n_perm)
    for k in range(n_perm):
        p = rng.permutation(s)
        null[k] = np.abs(p[ii] - p[jj]).mean()
    return float(obs), float(null.mean()), float(null.std())


def run(seed, cond, positions=None, drive=DRIVE):
    kw = dict(seed=seed, drive=drive, gradual_growth=False,
              differentiation=0.0 if cond == "ВЫКЛ" else ETA)
    if positions is not None:
        kw["positions"] = positions
    if cond == "БЕЗ ТОКА":
        kw["transmission"] = False
    if cond == "БЕЗ СОСЕДЕЙ":
        kw["contact_radius"] = 0.001
    return simulate(**kw)


def main():
    conds = ["ВЫКЛ", "ВКЛ", "БЕЗ ТОКА", "БЕЗ СОСЕДЕЙ"]
    acc = {c: {"edge": [], "obs": [], "nullm": [], "nulls": [], "up": [],
               "deg": [], "std": []} for c in conds}
    rng = np.random.default_rng(12345)

    for seed in SEEDS:
        for c in conds:
            res = run(seed, c)
            s = res["state_s"]
            contacts = res["contacts"]
            frac = float(np.mean((s < EDGE) | (s > 1 - EDGE)))
            obs, nm, ns = edge_contrast(s, contacts, rng)
            acc[c]["edge"].append(frac)
            acc[c]["obs"].append(obs)
            acc[c]["nullm"].append(nm)
            acc[c]["nulls"].append(ns)
            acc[c]["up"].append(bool(obs > nm) if np.isfinite(obs) else False)
            acc[c]["deg"].append(float(contacts.sum(axis=1).mean()))
            acc[c]["std"].append(float(s.std()))

    print(f"{'условие':<14} | {'доля у краёв':>13} | {'разброс s':>10} | "
          f"{'соседей':>8} | {'|si-sj| набл.':>13} | {'нуль':>16} | {'выше нуля':>10}")
    for c in conds:
        a = acc[c]
        obs = np.array(a["obs"], dtype=float)
        nm = np.array(a["nullm"], dtype=float)
        ns = np.array(a["nulls"], dtype=float)
        ok = np.isfinite(obs)
        obs_s = f"{np.nanmean(obs):.4f}" if ok.any() else "нет связей"
        null_s = (f"{np.nanmean(nm):.4f} +- {np.nanmean(ns):.4f}"
                  if ok.any() else "-")
        print(f"{c:<14} | {np.mean(a['edge']):>13.3f} | {np.mean(a['std']):>10.4f} | "
              f"{np.mean(a['deg']):>8.2f} | {obs_s:>13} | {null_s:>16} | "
              f"{sum(a['up']):>6} из {len(SEEDS)}")

    # мера 3: та же геометрия, другой шум
    print("\nТА ЖЕ ГЕОМЕТРИЯ, ДРУГОЙ ШУМ (позиции и drive неизменны):")
    base_seed = SEEDS[0]
    rng0 = np.random.default_rng(base_seed)
    pos = rng0.uniform(0, 1, size=(N, 2))
    agrees = []
    a = run(base_seed, "ВКЛ", positions=pos)["state_s"]
    for other in SEEDS[1:]:
        b = run(other, "ВКЛ", positions=pos)["state_s"]
        agree = float(np.mean((a > 0.5) == (b > 0.5)))
        agrees.append(agree)
    print(f"  согласие состояний между прогонами: {np.mean(agrees):.3f} "
          f"(мин {min(agrees):.3f}, макс {max(agrees):.3f}) на {len(agrees)} парах")

    thr = int(np.ceil(len(SEEDS) * 5 / 6))
    print(f"\nЧТЕНИЕ ПО ОБЪЯВЛЕННОМУ ПРАВИЛУ (порог {thr} из {len(SEEDS)}):")
    e_on = np.mean(acc["ВКЛ"]["edge"])
    e_no = np.mean(acc["БЕЗ СОСЕДЕЙ"]["edge"])
    print(f"  доля у краёв в ВКЛ: {e_on:.3f} "
          f"({'не ниже 2/3' if e_on >= 2/3 else 'НИЖЕ 2/3'})")
    print(f"  БЕЗ СОСЕДЕЙ: {e_no:.3f} = {e_no / e_on if e_on else float('nan'):.2f} от ВКЛ -- "
          f"{'не более трети: соперничество необходимо' if e_on > 0 and e_no <= e_on / 3 else 'ВЫШЕ ТРЕТИ: расхождение даёт самоусиление, не соперничество'}")
    print(f"  |si-sj| выше нуля: {sum(acc['ВКЛ']['up'])} из {len(SEEDS)} "
          f"({'подтверждено' if sum(acc['ВКЛ']['up']) >= thr else 'НЕ ПОДТВЕРЖДЕНО'})")
    print(f"  согласие при другом шуме: {np.mean(agrees):.3f} "
          f"({'ниже единицы -- не считывание геометрии' if np.mean(agrees) < 0.9 else 'БЛИЗКО К ЕДИНИЦЕ: картина задана геометрией'})")


if __name__ == "__main__":
    main()
