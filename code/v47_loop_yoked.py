"""v0.47: меняется ли ткань оттого, что петля ЗАМКНУТА -- с привязкой,
которая на этот раз не вырождена.

ОТКУДА. v0.46 замкнул петлю и показал, что она живая: ткань сдвигает мир
(средний u 0.740 при разомкнутой петле против 0.679 при замкнутой). Но
измерение провалилось по трём причинам, и все три здесь исправлены.

  1. ПРИВЯЗКА БЫЛА ВЫРОЖДЕНА (ошибка №47). Ткани проигрывалась ЕЁ ЖЕ
     запись при том же сиде. Модель детерминирована: вход тот же ->
     разряды те же -> всё то же. Сравнивался прогон с самим собой.
     ЗДЕСЬ: запись, снятая с ткани A, проигрывается ткани B. История
     входа совпадает по составу, причинной связи с собственной
     активностью B у неё нет.
  2. ПРОВЕРКА НЕ МОГЛА ПРОВАЛИТЬСЯ (ошибка №48). Она сравнивала записи в
     тех точках, где проигрывание закреплено по построению.
     ЗДЕСЬ проверка ПЕРЕВЁРНУТА: разряды у замкнутой и привязанной ткани
     ОБЯЗАНЫ РАЗЛИЧАТЬСЯ. Совпали -- условий нет, вердикт не выносится.
  3. ОТКЛИК БЫЛ У ПОЛА (0.011, отсев 15-17 сидов из 20). Причина нашлась
     не в читающей области, которую я трижды правил, а в стыке: проба
     брала силу связи из постоянной и шла при 10, тогда как ткань
     развивалась при 14 -- в режиме, где сигнал не путешествует
     (семейство ошибки №34). Исправлено: проба идёт при силе самой ткани.
     Отклик стал 0.33, отсев 4 из 20.

ЗАДАЧА ЧТЕНИЯ подобрана так, чтобы не упереться в потолок (ошибка №39).
Развёртка по расстоянию между состояниями мира:

    0.30/0.70 -- точность 0.927 (потолок, геометрия решает даром)
    0.40/0.60 -- 0.866
    0.44/0.56 -- 0.798
    0.47/0.53 -- 0.721  <- взято

ПРЕДСКАЗАНИЕ: в замкнутой петле собственная активность ткани
ПРЕДШЕСТВУЕТ сдвигу входа -- между действием и ощущением возникает
совпадение во времени. Пластичность опирается именно на совпадение
(v0.31, v0.36, v0.44), значит замкнутая ткань должна читаться лучше
привязанной.

ПРАВИЛО ЧТЕНИЯ, объявлено до запуска:
  * порог 2 п.п. (шум меры, урок №42), доля сидов с биномиальным p;
  * оба края: контроль вне 0.52-0.85 -- вердикт не выносится (№39);
  * перемешанные метки 0.42-0.58 (№40);
  * ПЕРЕВЁРНУТАЯ ПРОВЕРКА: доля сидов, где разряды замкнутой и
    привязанной ткани совпали побитово, обязана быть 0. Иначе условий
    нет;
  * плотность связей между условиями не больше 10%;
  * сообщается, насколько ткань сдвинула мир: без этого неизвестно, была
    ли петля замкнута на деле.
"""
import sys

import numpy as np

sys.path.insert(0, "code")
import v31_learned_readability as v31
import v37_self_built as v37
import v46_closed_loop as v46
from sim_core import simulate

N = v31.N
SEEDS = list(range(5601, 5651))
DUR, RATE, COUP = 24.0, 0.10, 14.0
LO, HI, XFAR = 0.47, 0.53, 0.50
MIN_EFFECT = 0.02

BASE = {k: v for k, v in v37.GROWN.items()
        if k not in ("div_rate", "coupling")}


def run(seed, world):
    return simulate(seed=seed, stimulus=[v46.touch], stimulus_amp=0.4,
                    stimulus_period=0.2, duration=DUR, div_rate=RATE,
                    coupling=COUP, world=world, world_init=0.5,
                    activity_memory=0.05, **BASE)


def read_net(net, seed):
    pos = net["positions"]
    alive = np.isfinite(net["birth"])
    p1 = np.where(alive & v46.touch(pos, LO))[0]
    p2 = np.where(alive & v46.touch(pos, HI))[0]
    read = np.where(alive & (pos[:, 0] > XFAR))[0]
    if len(p1) < 3 or len(p2) < 3 or len(read) < 10:
        return None
    C = net["contacts"] | net["contacts"].T
    f, a, nl = v31.measure(net, p1, p2, read, seed + 77)
    if a is None:
        return None
    return f, a, nl, float(C.sum(axis=1).mean())


def main():
    closed = {}
    for seed in SEEDS:                       # первый проход: замкнутые
        r = run(seed, v46.live_world)
        if len(r["world"]):
            closed[seed] = r
    keys = sorted(closed)
    res = {c: {"acc": [], "nul": [], "frac": [], "deg": [], "u": []}
           for c in ("ЗАМКНУТО", "ПРИВЯЗАНО")}
    same_spikes = 0
    skipped = 0
    for i, seed in enumerate(keys):           # второй: привязка к ЧУЖОЙ записи
        donor = keys[(i + 1) % len(keys)]
        a = closed[seed]
        b = run(seed, v46.replay_world(closed[donor]["world"], 0.001))
        if np.array_equal(a["spikes"], b["spikes"]):
            same_spikes += 1
        ra, rb = read_net(a, seed), read_net(b, seed)
        if ra is None or rb is None:
            skipped += 1
            continue
        for name, (f, ac, nl, deg), net in (("ЗАМКНУТО", ra, a),
                                            ("ПРИВЯЗАНО", rb, b)):
            res[name]["frac"].append(f); res[name]["acc"].append(ac)
            res[name]["nul"].append(nl); res[name]["deg"].append(deg)
            res[name]["u"].append(float(net["world"][:, 1].mean()))

    n = len(res["ЗАМКНУТО"]["acc"])
    print(f"{len(SEEDS)} сидов ({n} в счёт, {skipped} отброшено); "
          f"развитие {DUR:.0f} с, связь {COUP:g}, высоты {LO}/{HI}\n")
    if n == 0:
        print("  мерить не на чем")
        return
    print(f"{'условие':<11} | {'соседей':>7} | {'средний u':>9} | {'отклик':>7} | "
          f"{'точность':>8} | {'перемеш.':>8}")
    for c in res:
        r = res[c]
        print(f"{c:<11} | {np.mean(r['deg']):7.2f} | {np.mean(r['u']):9.3f} | "
              f"{np.mean(r['frac']):7.3f} | {np.mean(r['acc']):8.3f} | "
              f"{np.mean(r['nul']):8.3f}")
    a = np.array(res["ЗАМКНУТО"]["acc"]); b = np.array(res["ПРИВЯЗАНО"]["acc"])
    nul_all = np.mean(res["ЗАМКНУТО"]["nul"] + res["ПРИВЯЗАНО"]["nul"])
    dg = np.mean(res["ЗАМКНУТО"]["deg"]); db = np.mean(res["ПРИВЯЗАНО"]["deg"])
    mism = abs(dg - db) / db
    k = int((a > b).sum()); p = v31.p_ge(k, n)
    print(f"\nпроверки: сидов с ПОБИТОВО ОДИНАКОВЫМИ разрядами {same_spikes} "
          f"(обязано быть 0); плотность расходится на {mism * 100:.2f}%; "
          f"перемешанные метки {nul_all:.3f}")
    print(f"\nЧТЕНИЕ ({n} сидов):")
    print(f"  замкнутая выше привязанной: {k} из {n}, p = {p:.4f} "
          f"({b.mean():.3f} -> {a.mean():.3f}, {(a - b).mean() * 100:+.2f} п.п.)")
    if same_spikes:
        print("  УСЛОВИЯ СОВПАДАЮТ ПОБИТОВО -- сравнивать нечего")
    elif mism > 0.10:
        print("  ПЛОТНОСТЬ НЕ ВЫРАВНЕНА -- вердикт не выносится")
    elif not (0.42 <= nul_all <= 0.58):
        print(f"  перемешанные метки {nul_all:.3f} -- мера неисправна")
    elif not (0.52 <= b.mean() <= 0.85):
        print(f"  контроль {b.mean():.3f} вне 0.52-0.85 -- вердикт не выносится")
    elif abs((a - b).mean()) < MIN_EFFECT:
        print(f"  разница меньше порога {MIN_EFFECT * 100:.0f} п.п. -- "
              "замыкание петли на читаемость НЕ ВЛИЯЕТ")
    elif p < 0.05:
        print("  ЗАМЫКАНИЕ ПЕТЛИ МЕНЯЕТ ТКАНЬ: та же история входа, но без "
              "влияния на неё, даёт меньше")
    else:
        print("  величина выше порога, но знак неустойчив")


if __name__ == "__main__":
    main()
